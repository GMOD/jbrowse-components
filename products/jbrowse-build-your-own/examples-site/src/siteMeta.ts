// What each demo settles at, in px. Every demo here is `client:only`, so the
// server sends an empty `<div class="demo">` — `astro-island` is
// `display: contents` and adds no box of its own — and the browser fetches
// ~460 KB of engine before anything fills it. Without a reservation that box is
// 0 high until then and everything below it jumps down when the demo arrives.
//
// Generated by `pnpm measure-demo-heights`, which loads every built page and
// measures what its demo settles at, at two widths, keeping the taller. Don't
// hand-edit it: the figures are only worth anything while they match what the
// browser does, and `pnpm smoke` re-measures each demo against the reservation
// the page actually shipped on every run — so a number that drifts is a build
// failure rather than a page that quietly jumps again.
//
// Most of them hold at any width, because a display takes its height from its
// track config. The exception is a demo whose own controls wrap: reserve the
// **tallest** it gets, since a reservation that is too small jumps the page,
// while one that is too large only leaves space inside the demo's own border.
// `drive-it-from-your-app` is the one here — 253px wide, 286px once its control
// row wraps, so 286 is what it reserves.
//
// A demo whose height depends on its *data* — anything in a fit-height mode —
// cannot be pinned this way at all. Reserve the common case and accept the
// shift, or give that one a fixed-height box.
//
// Widened from the generated literal type on purpose: the templates look these
// up by a slug that is only known to be a string, and a slug with no entry yet
// should read as `undefined` (no reservation, and `pnpm smoke` says so) rather
// than fail to compile.
export const demoHeights: Record<string, number> = generated
