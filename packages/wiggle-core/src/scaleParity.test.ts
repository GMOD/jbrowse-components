// What **real d3-scale 4.0.2** answers, recorded by running it — not what the
// chainable port these pure functions replaced answered. That port diverged
// from d3 twice, and a table generated from it would have pinned the
// divergences as if they were the specification:
//
//   [-100, -1]  A negative log domain. d3 reflects the log/pow pair and nices
//               it to [-128, -1]; the port returned NaN and no ticks.
//   log values  d3 maps them through the natural log whatever the base, keeping
//               the base-specific pair for nice() and ticks() only. The base
//               cancels algebraically, so the port's log2 agreed to about
//               fifteen digits and differed in the last bit.
//
// A mixed-sign log domain is here for a fourth: d3 reflects on `domain[0]`
// alone, so [-10, 10] takes the negative path and the upper logarithm comes out
// NaN. It ticks that as an empty array — and since every comparison against NaN
// is false, `!(a < b)` and `a >= b` send it down different branches, the second
// inventing linear ticks for a domain d3 declines to tick.
//
// [5, 5] is here for a third divergence, a degenerate domain — what a flat
// coverage track hands over. d3 commits a niced domain only where the tick step
// converges and leaves that one alone; returning the loop's intermediate values
// gives the axis NaN endpoints.
//
// **The probes and the ranges are load-bearing.** Endpoints and midpoints on a
// single ascending range agree under rewrites that are wrong: dropping the
// descending-domain swap, or writing the interpolation as the algebraically
// identical `r0 + t * (r1 - r0)`, passed an earlier version of this table
// completely. What separates them is an interior probe off any round fraction,
// on a range that starts somewhere other than zero, and a descending range.
//
// To extend: `npm i d3-scale@4.0.2` somewhere scratch and print the same
// answers. Never regenerate from this module's own output.
