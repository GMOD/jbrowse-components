import {
  inputsHash,
  readStamp,
  significantText,
  stampArtifact,
} from './stamp.ts'

const shader = (source: string) => ({ path: 'p/a.slang', source })

const SOURCE = [
  '//! blend: max',
  'import hpmath;',
  'float f(float x) {',
  '  return x * 2.0;',
  '}',
].join('\n')

test('a comment, a blank line or an indent leaves the hash alone', () => {
  const edited = [
    '// a new comment',
    '//! blend: max',
    '',
    'import hpmath; // why',
    '/* a block',
    '   comment */',
    'float f(float x) {',
    '      return x * 2.0;',
    '}',
  ].join('\r\n')
  expect(inputsHash('v1', shader(edited), [])).toBe(
    inputsHash('v1', shader(SOURCE), []),
  )
})

test('code, a directive, an import, the path or the compiler move it', () => {
  const base = inputsHash('v1', shader(SOURCE), [])
  const moved = [
    inputsHash('v1', shader(SOURCE.replace('2.0', '3.0')), []),
    inputsHash('v1', shader(SOURCE.replace('max', 'add')), []),
    inputsHash('v1', shader(SOURCE), [{ path: 'p/hpmath.slang', source: 'x' }]),
    inputsHash('v1', { path: 'p/b.slang', source: SOURCE }, []),
    inputsHash('v2', shader(SOURCE), []),
  ]
  expect(new Set([base, ...moved]).size).toBe(moved.length + 1)
})

test('the import order does not move it', () => {
  const a = { path: 'p/a.slang', source: 'a' }
  const b = { path: 'p/b.slang', source: 'b' }
  expect(inputsHash('v1', shader(SOURCE), [a, b])).toBe(
    inputsHash('v1', shader(SOURCE), [b, a]),
  )
})

test('preprocessor lines stay lines', () => {
  expect(significantText('#define X 1\nfoo')).not.toBe(
    significantText('#define X 1 foo'),
  )
})

test('a stamp goes under the banner and reads back', () => {
  const contents = [
    '// AUTO-GENERATED by x from a.slang.',
    '// Do not edit.',
    '',
    'export const A = 1',
  ].join('\n')
  const stamped = stampArtifact(contents, '0123456789abcdef', 'p/a.slang')
  expect(stamped.split('\n').slice(0, 4)).toEqual([
    '// AUTO-GENERATED by x from a.slang.',
    '// Do not edit.',
    '// inputs: 0123456789abcdef p/a.slang',
    '',
  ])
  expect(readStamp(stamped)).toEqual({
    hash: '0123456789abcdef',
    slangPath: 'p/a.slang',
  })
  expect(readStamp(contents)).toBeUndefined()
  expect(() => stampArtifact('export const A = 1', 'x', 'p/a.slang')).toThrow(
    'banner',
  )
})
