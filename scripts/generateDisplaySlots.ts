// Writes packages/launch-args/src/displaySlots.generated.ts: each display
// type's config slot paths, read off the committed config JSON schema, so a
// track modifier lands only where the opened display declares the slot it
// writes. Rides `pnpm autogen`, after the config schema manifest.
import { readFileSync } from 'node:fs'
import path from 'node:path'

import { checkOrWriteAll } from '../website/scripts/check-utils.ts'
import { slotPathsByType } from './configSlotPaths.ts'

const ROOT = path.resolve(import.meta.dirname, '..')
const { version } = JSON.parse(
  readFileSync(path.join(ROOT, 'products/jbrowse-web/package.json'), 'utf8'),
) as { version: string }
const major = version.split('.')[0]
const schema = JSON.parse(
  readFileSync(
    path.join(ROOT, `website/static/schema/v${major}/config.json`),
    'utf8',
  ),
)

// Deep enough to tell whether a display has a setting at all; a path below the
// cut reads as inside the slot it was cut at.
const DEPTH = 3

const byType = [...slotPathsByType(schema)]
  .filter(([type]) => type.endsWith('Display'))
  .map(
    ([type, paths]) =>
      [
        type,
        [
          ...new Set(
            [...paths].map(p =>
              p
                .replace(/=.*$/, '')
                .replaceAll('[]', '')
                .split('.')
                .slice(0, DEPTH)
                .join('.'),
            ),
          ),
        ].sort(),
      ] as const,
  )
  .sort(([a], [b]) => a.localeCompare(b))

const body = byType
  .map(([type, paths]) => `  ${type}: ${JSON.stringify(paths)},`)
  .join('\n')

checkOrWriteAll(
  [
    {
      path: path.join(
        ROOT,
        'packages/launch-args/src/displaySlots.generated.ts',
      ),
      label: 'displaySlots.generated.ts',
      content: `// Generated by scripts/generateDisplaySlots.ts from the committed config
// schema — do not edit by hand. Regenerate with \`pnpm autogen\`.

/** Each display type's config slot paths, three segments deep, a list's members under its name. */
export const displaySlotPaths: Record<string, readonly string[]> = {
${body}
}
`,
    },
  ],
  'run `node --experimental-strip-types scripts/generateDisplaySlots.ts`',
)
