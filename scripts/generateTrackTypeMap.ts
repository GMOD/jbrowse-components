// Emits the adapter -> track type map the add-track guessers and `jbrowse
// add-track` share, from the `#trackType` tag every adapter's config schema
// already carries. Rides `pnpm autogen`; run directly after adding an adapter:
//
//   node --experimental-strip-types scripts/generateTrackTypeMap.ts
//
// The tag is the definition site — `website/scripts/api-docs/
// generateFileTypeDocs.ts` builds the "Supported file types" table off it.
// Generated rather than read because a JSDoc tag does not survive to runtime,
// `@jbrowse/add-track-core` carries no dependencies, and the CLI parses no
// TypeScript. ADR-077.
//
// A `#trackType` value is kept only when some config schema declares
// `#config <that name>`, which is what drops `TextSearchAdapter` — a real tag
// naming the slot a text-search adapter is configured under, and not a track.
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import path from 'node:path'

import { checkOrWrite } from '../website/scripts/check-utils.ts'

const REPO_ROOT = path.resolve(import.meta.dirname, '..')
const OUT = path.join(
  REPO_ROOT,
  'packages/add-track-core/src/trackTypes.generated.ts',
)

const files = execFileSync(
  'git',
  ['ls-files', 'packages', 'plugins', 'products'],
  { cwd: REPO_ROOT, encoding: 'utf8' },
)
  .split('\n')
  .filter(f => f.endsWith('.ts') || f.endsWith('.tsx'))
  // git lists a deletion until it is staged, and autogen runs before the commit
  .filter(f => existsSync(path.join(REPO_ROOT, f)))

const configNames = new Set<string>()
const trackTypeOf = new Map<string, string>()

for (const file of files) {
  const text = readFileSync(path.join(REPO_ROOT, file), 'utf8')
  if (!text.includes('#config')) {
    continue
  }
  for (const match of text.matchAll(/\/\*\*([\s\S]*?)\*\//g)) {
    const block = match[1] ?? ''
    const name = /#config\s+(\S+)/.exec(block)?.[1]
    if (!name) {
      continue
    }
    configNames.add(name)
    const trackType = /#trackType\s+(\S+)/.exec(block)?.[1]
    if (trackType) {
      const seen = trackTypeOf.get(name)
      if (seen && seen !== trackType) {
        throw new Error(
          `${file}: ${name} is tagged #trackType ${trackType} here and ${seen} elsewhere`,
        )
      }
      trackTypeOf.set(name, trackType)
    }
  }
}

const entries = [...trackTypeOf]
  .filter(([, trackType]) => configNames.has(trackType))
  .sort(([a], [b]) => a.localeCompare(b))

if (!entries.length) {
  throw new Error('no #trackType tags found; the scan is broken, not the tree')
}

checkOrWrite({
  path: OUT,
  label: `${path.relative(REPO_ROOT, OUT)} (${entries.length} adapters)`,
  staleHint: 'run `pnpm autogen`',
  content: `// Generated by scripts/generateTrackTypeMap.ts — do not edit by hand.
// Regenerate with \`pnpm autogen\` after adding or retagging an adapter.

/**
 * The track type each adapter's features are drawn by, from the \`#trackType\`
 * tag on its config schema. An adapter absent here has no tag, and the guessers
 * fall back to \`FeatureTrack\`.
 */
export const adapterTypesToTrackTypeMap: Record<string, string> = {
${entries.map(([adapter, trackType]) => `  ${adapter}: '${trackType}',`).join('\n')}
}
`,
})
