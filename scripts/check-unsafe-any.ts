// Fails when app source gains a use of an `any` value that typescript-eslint's
// no-unsafe-* rules flag: a member read, call, argument, assignment or return
// off something TypeScript gave up checking. The rules are off in the lint
// config, since turning them on means fixing every existing hit first; this
// holds the count instead, so a fix stays fixed and a new `any` fails CI.
//
// Counted per file and rule, so a fix in one file cannot pay for a new `any` in
// another. It fails only when a count grows; when one drops it says so, and
// `--write` lowers the baseline, which is the reason to give in the commit.
//
// App source only: tests, scripts, benches and example sites stay out, as they
// read fixtures and fetched JSON as `any` on purpose.
import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const baselinePath = join(root, 'scripts', 'unsafeAnyBaseline.txt')

const RULES = [
  'no-unsafe-member-access',
  'no-unsafe-call',
  'no-unsafe-argument',
  'no-unsafe-assignment',
  'no-unsafe-return',
]

const NOT_APP_SOURCE =
  /\.test\.|\/tests?\/|\/__tests__\/|testUtils?\.|test_util|\/browser-tests\/|\/benches\/|\/scripts\/|\/examples-site\/|\/lambda\//

function isAppSource(file: string) {
  return /\.tsx?$/.test(file) && !NOT_APP_SOURCE.test(file)
}

const run = spawnSync(
  join(root, 'node_modules/.bin/oxlint'),
  [
    '--type-aware',
    '-A',
    'all',
    ...RULES.flatMap(rule => ['-D', `typescript/${rule}`]),
    '-f',
    'unix',
    'packages',
    'plugins',
    'products',
  ],
  { cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 },
)
if (run.error) {
  throw run.error
}

// `path:line:col: message [Error/typescript(rule)]`
const hits = run.stdout.split('\n').flatMap(line => {
  const m = /^([^:]+):\d+:\d+: .*typescript\(([a-z-]+)\)\]$/.exec(line)
  return m && isAppSource(m[1]!) ? [{ file: m[1]!, rule: m[2]!, line }] : []
})
if (hits.length === 0 && run.status !== 0) {
  throw new Error(`oxlint reported nothing it could parse:\n${run.stderr}`)
}

const keyOf = (file: string, rule: string) => `${rule} ${file}`
const counts = new Map<string, number>()
for (const { file, rule } of hits) {
  const key = keyOf(file, rule)
  counts.set(key, (counts.get(key) ?? 0) + 1)
}

function readBaseline() {
  const baseline = new Map<string, number>()
  for (const line of readFileSync(baselinePath, 'utf8').split('\n')) {
    const m = /^(\d+) (\S+) (\S+)$/.exec(line)
    if (m) {
      baseline.set(keyOf(m[3]!, m[2]!), Number(m[1]))
    }
  }
  return baseline
}

const total = (map: Map<string, number>) =>
  [...map.values()].reduce((a, b) => a + b, 0)

if (process.argv.includes('--write')) {
  const byFileThenRule = (key: string) => key.split(' ').reverse().join(' ')
  const rows = [...counts]
    .sort(([a], [b]) =>
      byFileThenRule(a).localeCompare(byFileThenRule(b), 'en'),
    )
    .map(([key, count]) => `${count} ${key}`)
  writeFileSync(
    baselinePath,
    [
      '# Uses of an `any` value in app source, per rule and file: count, rule, file.',
      '# Generated by `node --experimental-strip-types scripts/check-unsafe-any.ts --write`.',
      '# scripts/check-unsafe-any.ts fails when a count grows; lower it, never raise it.',
      ...rows,
      '',
    ].join('\n'),
  )
  console.log(`wrote scripts/unsafeAnyBaseline.txt: ${total(counts)} uses`)
  process.exit(0)
}

const baseline = readBaseline()
const grown = [...counts].filter(
  ([key, count]) => count > (baseline.get(key) ?? 0),
)
if (grown.length > 0) {
  const grownKeys = new Set(grown.map(([key]) => key))
  console.error(
    [
      'Uses of `any` grew in app source:',
      '',
      ...grown.map(
        ([key, count]) => `  ${key}: ${baseline.get(key) ?? 0} -> ${count}`,
      ),
      '',
      ...hits
        .filter(({ file, rule }) => grownKeys.has(keyOf(file, rule)))
        .map(({ line }) => `  ${line}`),
      '',
      'Type the value instead: a typed helper, a narrowing check, or `unknown` and a',
      "guard. The baseline only goes down; see this script's header.",
    ].join('\n'),
  )
  process.exit(1)
}

const before = total(baseline)
const now = total(counts)
console.log(
  now < before
    ? `${now} uses of \`any\` in app source, down from ${before}: run with --write to lower the baseline`
    : `${now} uses of \`any\` in app source, none new`,
)
