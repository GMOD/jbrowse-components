#!/usr/bin/env -S node --experimental-strip-types

// Bundles the R helper library into the TS artifact the exporter emits from:
//
//   plugins/marks/src/rexport/rhelpers/*.R
//     -> plugins/marks/src/rexport/rHelpers.generated.ts
//
// The helpers live as real .R files so R tooling can parse, lint and run them,
// and so their source needs no TS-template escaping (`"\\.cram$"` here is what
// R sees). This bundles them verbatim; it is not a translator, and extending it
// into one reverses a decision (agent-docs/reference/R_EXPORT.md).
//
// A helper's file name is the name a mark requests it by. `--check` verifies
// the artifact without writing it.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
)
const DIR = path.join(REPO_ROOT, 'plugins/marks/src/rexport')
const SRC = path.join(DIR, 'rhelpers')
const OUT = path.join(DIR, 'rHelpers.generated.ts')

const names = readdirSync(SRC)
  .filter(f => f.endsWith('.R'))
  .map(f => path.basename(f, '.R'))
  .sort()

for (const name of names) {
  const body = readFileSync(path.join(SRC, `${name}.R`), 'utf8')
  if (!new RegExp(`^${name} <- `, 'm').test(body)) {
    throw new Error(
      `${name}.R does not define \`${name}\` at top level: a helper's file name is the name a mark requests it by`,
    )
  }
}

const entries = names
  .map(name => {
    const body = readFileSync(path.join(SRC, `${name}.R`), 'utf8').trimEnd()
    return `  ${name}: ${JSON.stringify(body)},`
  })
  .join('\n')

const generated = `// AUTO-GENERATED by scripts/build-r-helpers.ts from rhelpers/*.R.
// Do not edit. Edit the .R sources and run \`pnpm gen:rhelpers\`.

/**
 * The inline R helper definitions the exporter can emit, keyed by the name a
 * mark requests one by. A script carries only the helpers it references, so a
 * reader gets plain rtracklayer and ggplot2 they can edit in place.
 */
export const HELPERS: Record<string, string> = {
${entries}
}
`

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== generated) {
    console.error(
      `Error: ${path.relative(REPO_ROOT, OUT)} is out of date.\nRun 'pnpm gen:rhelpers' and commit the result.`,
    )
    process.exit(1)
  }
  console.log(`${names.length} R helpers up to date`)
} else {
  writeFileSync(OUT, generated)
  console.log(
    `wrote ${path.relative(REPO_ROOT, OUT)} (${names.length} helpers)`,
  )
}
