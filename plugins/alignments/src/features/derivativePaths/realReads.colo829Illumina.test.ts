function run() {
  // one fetch result per displayed region, which is what the app hands the
  // chain builder: `groupReadsByName` stamps each entry with its REGION's
  // refName, so the split has to happen here too
  const rpcDataMap = new Map(
    REGIONS.map(region => [
      region.displayedRegionIndex,
      pileupDataFromSamRecords(READS.filter(r => r.ref === region.refName)),
    ]),
  )
  const chains = computeReadChains(rpcDataMap, REGIONS)
  return { chains, candidates: computeDerivativePaths({ chains }) }
}

// The junction a two-segment candidate describes: the first segment's read-exit
// edge and the second's read-entry edge, as breakend coordinates.
function junctionOf(candidate: {
  segments: { start: number; end: number; strand: number; refName: string }[]
}) {
  const [a, b] = candidate.segments
  return {
    [a!.refName]: a!.strand === -1 ? a!.start + 1 : a!.end,
    [b!.refName]: b!.strand === -1 ? b!.end : b!.start + 1,
  } as Record<string, number>
}

