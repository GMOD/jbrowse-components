function candidates() {
  return computeDerivativePaths({
    chains: computeReadChains(
      [new Map([[0, pileupDataFromSamRecords(READS)]])],
      [REGION],
    ),
  })
}

describe('K562 BCR--ABL1 from Iso-Seq reads', () => {
  it('ranks the routes by the number of reads describing each', () => {
    const found = candidates()
    expect(found.map(c => c.readCount)).toEqual([36, 5, 5, 3, 2])
    // every one of them is the same two-hop shape, chr22 out and chr9 in
    for (const candidate of found) {
      expect(candidate.refNames).toEqual(['chr22', 'chr9'])
      expect(candidate.segments).toHaveLength(2)
    }
  })

  it('puts every route through the published BCR breakpoint', () => {
    // The junction edges carry no flank (only the outer edges grow), so these
    // are the reads' own junction coordinates, and they agree to within the
    // bucketing tolerance across all five routes.
    const exits = candidates().map(c => c.segments[0]!.end)
    expect(Math.max(...exits) - Math.min(...exits)).toBeLessThanOrEqual(20)
    for (const exit of exits) {
      expect(exit).toBeGreaterThanOrEqual(BCR_BREAKPOINT.start)
      expect(exit).toBeLessThanOrEqual(BCR_BREAKPOINT.end)
    }
  })

  it('splits them apart at the ABL1 end, one row per acceptor', () => {
    // Transcripts, so a read's second alignment starts at whichever ABL1 exon
    // its isoform splices into. The chr22 side above is one base; this side is
    // five distinct positions spread over tens of kilobases, which is what
    // turns one fusion into five rows.
    const entries = candidates().map(c => c.segments[1]!.start)
    expect(new Set(entries).size).toBe(entries.length)
    expect(Math.max(...entries) - Math.min(...entries)).toBeGreaterThan(50_000)
    // one of them is the acceptor STAR-Fusion called
    expect(
      entries.some(
        bp => bp >= ABL1_BREAKPOINT.start && bp <= ABL1_BREAKPOINT.end,
      ),
    ).toBe(true)
  })
})
