function run() {
  const chains = computeReadChains(
    [new Map([[0, pileupDataFromSamRecords(READS)]])],
    [REGION],
  )
  return { chains, candidates: computeDerivativePaths({ chains }) }
}

describe('paired-end short reads', () => {
  it('chains each mate separately, so a pair is not read as a junction', () => {
    // resolveReadGroup partitions a QNAME group into first and second in pair
    // and emits no segment for the mate link: two mates of one fragment are not
    // two hops of one molecule. Without that partition the two mates' segments
    // would concatenate into one chain and every pair would describe a
    // rearrangement.
    const { chains } = run()
    expect(chains).toHaveLength(126)
    // no chain spans more than one mate's worth of read
    for (const chain of chains) {
      const span = chain.reduce((sum, seg) => sum + (seg.end - seg.start), 0)
      expect(span).toBeLessThan(500)
    }
  })

  it('returns confidently ranked candidates that are all mapping artefacts', () => {
    const { candidates } = run()
    expect(candidates).toHaveLength(8)
    // more supporting reads than the real COLO829 der(3) has
    expect(candidates[0]!.readCount).toBeGreaterThan(26)
  })

  it('separates them from a real allele by span, which the picker already shows', () => {
    // Every segment of every candidate is a piece of a 150 bp read. The dialog
    // prints "N segments, X bp" per row, so the difference is on screen; it is
    // the ranking, which is by read count alone, that does not know it.
    const { candidates } = run()
    const longest = Math.max(
      ...candidates.flatMap(c => c.segments.map(seg => seg.end - seg.start)),
    )
    // the flank the candidate carries is 2000 each side, so bound the raw
    // segments rather than the drawn ones
    expect(longest - 2 * 2000).toBeLessThan(200)
  })
})
