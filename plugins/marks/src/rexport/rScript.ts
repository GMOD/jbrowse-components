import { HELPERS } from './rHelpers.generated.ts'
import { frameChain, packagesFor, renderPlot, rStr } from './rplot.ts'

import type { Plot, RFrame } from './rplot.ts'

/**
 * Helper to helper calls. A panel declares only what its own code calls, and
 * the closure adds the rest, so a caller of a reader never lists the region
 * machinery that reader sits behind.
 *
 * An edge missing here emits a script referencing a function it never defined.
 * `rScript.test.ts` scans the R bodies and fails on one.
 */
export const HELPER_DEPS: Record<string, string[]> = {
  read_regions: ['region_layout'],
}

export function resolveHelpers(names: readonly string[]) {
  const seen = new Set<string>()
  const walk = (name: string) => {
    if (seen.has(name)) {
      return
    }
    seen.add(name)
    for (const dep of HELPER_DEPS[name] ?? []) {
      walk(dep)
    }
  }
  for (const n of names) {
    walk(n)
  }
  return [...seen].sort()
}

export interface Region {
  refName: string
  start: number
  end: number
}

export interface Panel {
  variable: string
  plot: Plot
  helpers: readonly string[]
  /** Relative vertical share, carried from the display height. */
  heightWeight?: number
}

/** ggsave refuses a dimension over 50 inches, and a panel stack can ask for more. */
const MAX_INCHES = 50
const INCHES_PER_WEIGHT = 2

function regionsFrame(regions: readonly Region[]) {
  const col = (f: (r: Region) => string | number) => regions.map(f).join(', ')
  return `regions <- region_layout(data.frame(
  chrom = c(${col(r => rStr(r.refName))}),
  start = c(${col(r => r.start)}),
  end = c(${col(r => r.end)})))`
}

function figureHeight(panels: readonly Panel[]) {
  const weight = panels.reduce((a, p) => a + (p.heightWeight ?? 1), 0)
  return Math.min(MAX_INCHES, Math.max(2, weight * INCHES_PER_WEIGHT))
}

function stacked(panels: readonly Panel[]) {
  if (panels.length === 1) {
    return panels[0]!.variable
  }
  const weights = panels.map(p => p.heightWeight ?? 1).join(', ')
  return `${panels.map(p => p.variable).join(' / ')} +
  patchwork::plot_layout(heights = c(${weights}))`
}

/**
 * A whole script: libraries, the helpers the panels reached for, the region
 * layout, each panel's frame and plot, and the save.
 *
 * `notes` lands in the header rather than nowhere — a figure that quietly
 * differs from the view it claims to redraw is the failure worth the lines.
 */
export function assembleRScript({
  regions,
  panels,
  notes = [],
  out = 'figure.png',
}: {
  regions: readonly Region[]
  panels: readonly Panel[]
  notes?: readonly string[]
  out?: string
}) {
  const packages = new Set(['ggplot2'])
  for (const p of panels) {
    for (const pkg of packagesFor(p.plot)) {
      packages.add(pkg)
    }
  }
  if (panels.length > 1) {
    packages.add('patchwork')
  }
  const helpers = resolveHelpers(panels.flatMap(p => [...p.helpers]))
  // Keyed by the frame itself, not its name: a derived frame that keeps its
  // base's name is a second step over the same binding, and keying by name
  // dropped the read it builds on.
  const frames = new Set<RFrame>()
  for (const p of panels) {
    for (const l of p.plot.layers) {
      for (const f of frameChain(l.frame)) {
        frames.add(f)
      }
    }
  }
  return [
    '# Generated by JBrowse 2 — this script redraws the view from its own data.',
    '# Edit it: it is plain rtracklayer and ggplot2, with no bespoke package.',
    ...(notes.length
      ? [
          '#',
          '# What this figure does not show:',
          ...notes.map(n => `#   - ${n}`),
        ]
      : []),
    '',
    [...packages]
      .sort()
      .map(p => `library(${p})`)
      .join('\n'),
    '',
    helpers.map(h => HELPERS[h]).join('\n\n'),
    '',
    regionsFrame(regions),
    '',
    [...frames].map(f => f.statements).join('\n\n'),
    '',
    panels.map(p => renderPlot(p.variable, p.plot)).join('\n\n'),
    '',
    `ggsave(${rStr(out)}, ${stacked(panels)},
  width = 10, height = ${figureHeight(panels)}, dpi = 150, limitsize = FALSE)`,
    '',
  ].join('\n')
}
