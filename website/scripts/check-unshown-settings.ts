// Ratchets, per tutorial, the display settings the page tells the reader to
// change and then never shows: `unshown-settings.ts` says what counts.
//
// `check-figure-actions` holds the other half of the same rule, a figure
// arriving with no instruction before it. Together they say a tutorial's
// instructions and its pictures are the same list.
//
// Run `pnpm check-unshown-settings` to rewrite the list, and `--list` to print
// each flagged path with its line.
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { check, checkOrWrite, docFiles } from './check-utils.ts'
import { docRelative, docsDir } from './paths.ts'
import { unshownSettings } from './unshown-settings.ts'

const listFile = join(import.meta.dirname, 'unshown-settings.txt')
const list = process.argv.includes('--list')

const HEADER = `# AUTO-GENERATED by scripts/check-unshown-settings.ts — do not edit by hand.
# Per-tutorial count of menu paths whose result no figure shows, in that
# section or the next, as "<doc> <count>". Regenerate with
# \`pnpm check-unshown-settings\`.
#
# A higher count is a regression: a setting the page tells the reader to change
# is a visual claim, so show what it does rather than describing it.
`

const counts = new Map<string, number>()
const detail = new Map<string, UnshownLine[]>()
interface UnshownLine {
  line: number
  path: string
}
for (const file of docFiles(join(docsDir, 'tutorials'))) {
  const rel = docRelative(file)
  const hits = unshownSettings(readFileSync(file, 'utf8'))
  if (hits.length > 0) {
    counts.set(rel, hits.length)
    detail.set(rel, hits)
    if (list) {
      for (const h of hits) {
        console.log(`${rel}:${h.line}: ${h.path}`)
      }
    }
  }
}
if (list) {
  process.exit(0)
}
const entries = [...counts].sort(([a], [b]) => a.localeCompare(b))
const content = `${HEADER}${entries.map(([doc, n]) => `${doc} ${n}`).join('\n')}\n`

if (check) {
  const committed = new Map(
    readFileSync(listFile, 'utf8')
      .split('\n')
      .filter(l => l && !l.startsWith('#'))
      .map(l => {
        const [doc, n] = l.split(' ')
        return [doc!, Number(n)] as const
      }),
  )
  const grew = entries.filter(([doc, n]) => n > (committed.get(doc) ?? 0))
  if (grew.length > 0) {
    console.error(
      `${grew.length} tutorial(s) gained a setting no figure shows:\n${grew
        .map(
          ([doc, n]) =>
            `  ${doc}: ${committed.get(doc) ?? 0} → ${n} (${detail
              .get(doc)!
              .map(h => `${h.line} ${h.path}`)
              .join(', ')})`,
        )
        .join(
          '\n',
        )}\n\nShow what the setting does, in its own section or the next one.`,
    )
    process.exit(1)
  }
}

checkOrWrite({
  path: listFile,
  content,
  label: `unshown-settings.txt (${entries.reduce((s, [, n]) => s + n, 0)} across ${entries.length} tutorials)`,
  staleHint: 'run `pnpm check-unshown-settings` to hold the gain',
})
