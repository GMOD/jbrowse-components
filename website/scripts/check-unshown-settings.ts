// Ratchets, per tutorial, the display settings the page tells the reader to
// change and then never shows: `unshown-settings.ts` says what counts.
//
// `check-figure-actions` holds the other half of the same rule, a figure
// arriving with no instruction before it. Together they say a tutorial's
// instructions and its pictures are the same list.
//
// Run `pnpm check-unshown-settings` to rewrite the list, and `--list` to print
// each flagged path with its line.
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { checkOrWrite, docFiles, ratchetDocCounts } from './check-utils.ts'
import { docRelative, docsDir } from './paths.ts'
import { unshownSettings } from './unshown-settings.ts'

const listFile = join(import.meta.dirname, 'unshown-settings.txt')
const list = process.argv.includes('--list')

const HEADER = `# AUTO-GENERATED by scripts/check-unshown-settings.ts — do not edit by hand.
# Per-tutorial count of menu paths whose result no figure shows, in that
# section or the next, as "<doc> <count>". Regenerate with
# \`pnpm check-unshown-settings\`.
#
# A higher count is a regression: a setting the page tells the reader to change
# is a visual claim, so show what it does rather than describing it.
`

const hits = new Map(
  docFiles(join(docsDir, 'tutorials')).map(file => [
    docRelative(file),
    unshownSettings(readFileSync(file, 'utf8')),
  ]),
)
if (list) {
  for (const [rel, docHits] of hits) {
    for (const h of docHits) {
      console.log(`${rel}:${h.line}: ${h.path}`)
    }
  }
  process.exit(0)
}

const { content, docs, total } = ratchetDocCounts({
  hits,
  header: HEADER,
  listFile,
  regression: 'tutorial(s) gained a setting no figure shows',
  describe: docHits =>
    ` (${docHits.map(h => `${h.line} ${h.path}`).join(', ')})`,
  advice: 'Show what the setting does, in its own section or the next one.',
})

checkOrWrite({
  path: listFile,
  content,
  label: `unshown-settings.txt (${total} across ${docs} tutorials)`,
  staleHint: 'run `pnpm check-unshown-settings` to hold the gain',
})
