// Ratchets the set of third-party hosts the figure specs fetch from.
//
// A figure sweep in CI pulls whatever its specs point at, so every host here is
// a server we do not run that a scheduled job depends on. The standing rule is
// that CI should not pull from remote repos; this does not pretend to enforce
// that outright, because the remaining entries are real data the figures are
// pictures of and each one has to be mirrored before it can go. What it stops
// is the set growing, which is the way a list like this normally gets worse:
// one spec at a time, each individually reasonable.
//
// Removing a line is the win. To remove one, mirror the asset onto jbrowse.org
// and repoint the spec. That also takes the figure off somebody else's uptime —
// `ld.ts` sets a 180s readyTimeout because UCSC's hgdownload "times out and
// refetches often enough to blow through 120s on a bad day", which is this list
// costing render time rather than only trust.
//
// KNOWN UNDERCOUNT, deliberately not papered over: a spec that loads a hosted
// UCSC hub config from jbrowse.org names no third-party host here, but the hub's
// tracks resolve to hgdownload, so the browser fetches from UCSC anyway. Seven
// of the spec files do that. The line for hgdownload therefore stands for more
// than the three URLs that spell it out, and mirroring the hubs is a bigger job
// than mirroring a file.
//
// Run `pnpm check-remote-hosts` to rewrite the list; CI runs `--check`.
import { join } from 'node:path'

import { checkOrWrite } from './check-utils.ts'
import { specs } from './screenshot-specs.ts'

const listFile = join(import.meta.dirname, 'third-party-hosts.txt')

// Ours, or not a fetch at all. Matched against `host/first-path-segment`, not
// the bare host, because a handful of specs address our own bucket path-style
// as `s3.amazonaws.com/jbrowse.org/...`; on the host alone those read as a
// third-party dependency on AWS, which they are not. (They are worth repointing
// at jbrowse.org anyway — path-style bypasses the CloudFront distribution — but
// that is a spec change, not this check's business.)
const OURS = [
  // subdomains too, matching check-external-links.ts's OUR_HOST: the
  // genomes_basics figures capture genomes.jbrowse.org's own catalog pages, and
  // that site is ours (~/src/jb2hubs) rather than a server we depend on
  /(^|\.)jbrowse\.org(\/|$)/,
  /^s3\.amazonaws\.com\/jbrowse\.org(\/|$)/,
  /^localhost(\/|$)/,
  /^127\.0\.0\.1(\/|$)/,
  /^example\.com(\/|$)/,
  /^google\.com(\/|$)/,
]

const HEADER = `# AUTO-GENERATED by scripts/check-remote-hosts.ts — do not edit by hand.
# Third-party hosts the figure specs fetch from, i.e. servers we do not run that
# a CI figure sweep therefore pulls from. Regenerate with \`pnpm check-remote-hosts\`.
#
# Adding a line is a regression. Removing one is the win, and the way to remove
# one is to mirror the asset onto jbrowse.org and repoint the spec — which also
# takes the spec off somebody else's uptime. ld.ts already carries a 180s
# readyTimeout for exactly this reason: "the anoGam3 hub's chrom.sizes off
# hgdownload.soe.ucsc.edu times out and refetches often enough to blow through
# 120s on a bad day."
#
# Note hgdownload's real reach is wider than its own line: the hosted UCSC hub
# configs on jbrowse.org name tracks that resolve back to hgdownload, so a spec
# loading one pulls from UCSC without naming it here.
`

// The specs as built, not their source text, so a URL a spec reads off a
// page's fence counts and one a comment cites does not. A session spec's URL
// carries its tracks percent-encoded, hence the decode.
function specText(spec: unknown) {
  const json = JSON.stringify(spec)
  try {
    return decodeURIComponent(json)
  } catch {
    return json
  }
}

const hosts = new Set<string>()
for (const spec of specs) {
  for (const m of specText(spec).matchAll(
    /https?:\/\/([a-zA-Z0-9.-]+)(\/[^"'`\s)]*)?/g,
  )) {
    const host = m[1]!
    const hostAndFirstSegment =
      host + (m[2] ?? '').split('/').slice(0, 2).join('/')
    if (!OURS.some(re => re.test(hostAndFirstSegment))) {
      hosts.add(host)
    }
  }
}

checkOrWrite({
  path: listFile,
  content: `${HEADER}${[...hosts].sort().join('\n')}\n`,
  label: 'third-party hosts in figure specs',
  staleHint:
    'a spec now fetches from a server we do not run. Mirror the asset onto ' +
    'jbrowse.org and repoint the spec, or run `pnpm check-remote-hosts` to ' +
    'record the new dependency deliberately.',
})
