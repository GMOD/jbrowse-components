// Ratchets, per tutorial, the figures and clips that arrive before their
// section tells the reader what to do: `figureActions.ts` says what counts as
// an instruction. A tutorial is a route the reader follows, and a figure with
// no location string, menu path, config, command or click before it in its
// section is a result shown to someone who was never told how to get there.
//
// Run `pnpm check-figure-actions` to rewrite the list, and `--list` to print
// each flagged tag with its line.
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { check, checkOrWrite, docFiles } from './check-utils.ts'
import { unpromptedTags } from './figure-actions.ts'
import { docRelative, docsDir } from './paths.ts'

const listFile = join(import.meta.dirname, 'figure-actions.txt')
const list = process.argv.includes('--list')

const HEADER = `# AUTO-GENERATED by scripts/check-figure-actions.ts — do not edit by hand.
# Per-tutorial count of <Figure> and <Video> tags with no instruction before
# them in their section, as "<doc> <count>". Regenerate with
# \`pnpm check-figure-actions\`.
#
# A higher count is a regression: before the tag, tell the reader the window
# to type, the menu path to take, the config to paste or the command to run.
`

const counts = new Map<string, number>()
const detail = new Map<string, number[]>()
for (const file of docFiles(join(docsDir, 'tutorials'))) {
  const rel = docRelative(file)
  const text = readFileSync(file, 'utf8')
  const tags = unpromptedTags(text)
  if (tags.length > 0) {
    counts.set(rel, tags.length)
    detail.set(
      rel,
      tags.map(t => t.line),
    )
    if (list) {
      const lines = text.split('\n')
      for (const t of tags) {
        console.log(`${rel}:${t.line}: ${lines[t.line - 1]!.slice(0, 100)}`)
      }
    }
  }
}
if (list) {
  process.exit(0)
}
const entries = [...counts].sort(([a], [b]) => a.localeCompare(b))
const content = `${HEADER}${entries.map(([doc, n]) => `${doc} ${n}`).join('\n')}\n`

if (check) {
  const committed = new Map(
    readFileSync(listFile, 'utf8')
      .split('\n')
      .filter(l => l && !l.startsWith('#'))
      .map(l => {
        const [doc, n] = l.split(' ')
        return [doc!, Number(n)] as const
      }),
  )
  const grew = entries.filter(([doc, n]) => n > (committed.get(doc) ?? 0))
  if (grew.length > 0) {
    console.error(
      `${grew.length} tutorial(s) gained a figure with no instruction before it:\n${grew
        .map(
          ([doc, n]) =>
            `  ${doc}: ${committed.get(doc) ?? 0} → ${n} (lines ${detail.get(doc)!.join(', ')})`,
        )
        .join(
          '\n',
        )}\n\nBefore the tag, in the same section, give the reader the window to type, the menu path to take, the config to paste or the command to run.`,
    )
    process.exit(1)
  }
}

checkOrWrite({
  path: listFile,
  content,
  label: `figure-actions.txt (${entries.reduce((s, [, n]) => s + n, 0)} across ${entries.length} tutorials)`,
  staleHint: 'run `pnpm check-figure-actions` to hold the gain',
})
