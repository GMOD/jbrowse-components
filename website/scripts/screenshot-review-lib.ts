// Directories scanned for doc usages of each image
const docRoots = ['docs', 'blog', 'src/pages'].map(d =>
  path.resolve(websiteDir, d),
)

export interface DocUsage {
  file: string // relative to websiteDir
  line: number
  caption: string // Figure caption / markdown alt text
}

// One PNG's review state — a whole figure, or one part of a composed figure.
// `autogenerated` means a generator (a generate-screenshots.ts spec, or a
// desktop capture) can reproduce it; otherwise it's a hand-captured image kept
// only in static/img (e.g. UI-flow walkthroughs, the gallery read-vs-ref shot)
// that must be re-captured by hand.
export interface ScreenshotPart {
  name: string
  usages: DocUsage[]
  autogenerated: boolean
  exists: boolean
  // In figures.lock but not on disk. Distinct from plain `!exists`, because the
  // fix is `pnpm figures:pull` rather than a regen — the bytes are in the store,
  // this checkout just has not fetched them.
  unpulled: boolean
  // Where the baseline picture lives: the store URL of whatever figures.lock on
  // origin/main names for this figure. Absent when the baseline has no such
  // figure, i.e. it was added on this branch. Immutable and public, so the page
  // links it straight rather than proxying the bytes.
  mainUrl?: string
  // present in the baseline but the working-tree pixels differ — i.e. an update
  // the current work introduced
  changed: boolean
}

export interface Screenshot extends ScreenshotPart {
  // for a compose figure, the part specs stacked into it; empty for every other
  // figure. Parts are ingredients rather than reviewable figures of their own,
  // so they appear here instead of as entries in their own right.
  parts: ScreenshotPart[]
}

function findMarkdownFiles() {
  return docRoots
    .filter(d => fs.existsSync(d))
    .flatMap(d => walkFiles(d, n => /\.mdx?$/.test(n)))
}

// gallery.ts is the single source of truth for /gallery/ (see
// website/CLAUDE.md); its items reference images via `spec`/`img` fields, not
// literal "/img/<name>.png" text, so it needs its own scan rather than being
// added to docRoots.
const galleryFile = path.resolve(websiteDir, 'src/lib/gallery.ts')

// Pull the caption="..." attribute out of a <Figure .../> line if present
function extractFigureCaption(line: string) {
  const m = /caption=("|')([\s\S]*?)\1/.exec(line)
  return m?.[2] ?? ''
}

// Pull the alt text out of a markdown image ![alt](src)
function extractMarkdownAlt(line: string) {
  const m = /!\[([^\]]*)\]/.exec(line)
  return m?.[1] ?? ''
}

// Every image-name a single line references. Matches the `/img/<name>.png`
// segment in any form the docs use — <Figure src="/img/x.png"/>,
// ![alt](/jb2/img/x.png), and absolute github-raw URLs that point back at this
// repo's website/static/img/x.png (used in blog posts so external aggregators
// resolve the image). Third-party github-raw images (jb2export, plugin-list)
// also match here but get dropped later because their PNG isn't on disk.
function imageNamesOnLine(line: string): string[] {
  const names: string[] = []
  const re = /\/img\/([A-Za-z0-9_/-]+)\.png/g
  let m: RegExpExecArray | null = re.exec(line)
  while (m) {
    names.push(m[1]!)
    m = re.exec(line)
  }
  return names
}

// Mirrors gallery.ts's itemImg(): an item's figure is its explicit `img`
// (".png" stripped), else its `spec` name. Field order in each object literal
// isn't guaranteed, so scan the whole item text rather than assuming img/spec
// comes after label.
function galleryItemImageName(itemText: string): string | undefined {
  const img = /\bimg:\s*(['"])([^'"]+)\1/.exec(itemText)
  if (img) {
    return img[2]!.replace(/\.png$/, '')
  }
  const spec = /\bspec:\s*(['"])([^'"]+)\1/.exec(itemText)
  return spec?.[2]
}

// One figure can be used by several docs, and one doc line by several figures,
// so every usage appends to its name's list.
function addUsage(
  index: Map<string, DocUsage[]>,
  name: string,
  usage: DocUsage,
) {
  const list = index.get(name)
  if (list) {
    list.push(usage)
  } else {
    index.set(name, [usage])
  }
}

// gallery.ts has no markup to walk line-by-line; instead split on each
// object literal `{ ... }` in the `items:` arrays and pull `label`/`img`/`spec`
// out of each. Good enough for gallery.ts's own flat, unnested item shape.
function scanGalleryUsages(): Map<string, DocUsage[]> {
  const index = new Map<string, DocUsage[]>()
  if (!fs.existsSync(galleryFile)) {
    return index
  }
  const rel = path.relative(websiteDir, galleryFile)
  const text = fs.readFileSync(galleryFile, 'utf8')
  const lines = text.split('\n')
  let itemStart = -1
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!
    if (/^\s*\{$/.test(line)) {
      itemStart = i
    } else if (/^\s*\},?$/.test(line) && itemStart >= 0) {
      const itemLines = lines.slice(itemStart, i + 1)
      const itemText = itemLines.join('\n')
      const name = galleryItemImageName(itemText)
      if (name) {
        const label = /\blabel:\s*(['"])([^'"]*)\1/.exec(itemText)?.[2] ?? ''
        const usage: DocUsage = {
          file: rel,
          line: itemStart + 1,
          caption: label,
        }
        addUsage(index, name, usage)
      }
      itemStart = -1
    }
  }
  return index
}

// Scan every markdown file once, building name -> usages. Re-reading per-name
// would be O(names × files); this is O(files).
function buildUsageIndex(): Map<string, DocUsage[]> {
  const index = scanGalleryUsages()
  for (const file of findMarkdownFiles()) {
    // a doc file can be deleted/regenerated between the directory walk and now
    // (e.g. autogen rewriting docs/config/*.md); a vanished file is just not a
    // usage, so skip it rather than crashing
    const text = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
    if (!text.includes('/img/')) {
      continue
    }
    const lines = text.split('\n')
    const rel = path.relative(websiteDir, file)
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i]!
      const names = imageNamesOnLine(line)
      if (names.length > 0) {
        const isFigure = line.includes('<Figure')
        const usage: DocUsage = {
          file: rel,
          line: i + 1,
          caption: isFigure
            ? extractFigureCaption(line)
            : extractMarkdownAlt(line),
        }
        for (const name of names) {
          addUsage(index, name, usage)
        }
      }
    }
  }
  return index
}

let usageIndex: Map<string, DocUsage[]> | undefined

function getUsageIndex() {
  if (!usageIndex) {
    usageIndex = buildUsageIndex()
  }
  return usageIndex
}

// jb2export writes its renders to products/jbrowse-img/img (the README/npm
// copy); the website mirror at static/img/jbrowse-img is only refreshed by a
// `pnpm screenshots` (captureCliSpec) or `pnpm autogen` run. So a fresh
// jb2export the reviewer just produced can leave the review tooling looking at
// the stale mirror. Self-heal on read: if the source render is newer than (or
// absent from) the mirror, copy it over before anyone hashes or serves it.
const jbrowseImgPrefix = 'jbrowse-img/'
const jbrowseImgSrcDir = path.resolve(
  websiteDir,
  '..',
  'products',
  'jbrowse-img',
  'img',
)

// Called on every read of a mirrored figure rather than once at startup: the
// hash and the bytes a reviewer is served have to agree, and a jb2export run
// mid-session is exactly the case this exists for. Two stats when there is
// nothing to do.
//
// mtime is the trigger, CONTENT is the decision — the same rule as `mirrorFile`
// in generate-screenshots.ts, which is the other half of this mirror and the
// reason the two must not drift. On mtime alone this was a write to the
// worktree performed by a GET, on a heuristic that `figures:pull` can lose:
// pull fetches both paths of a pair concurrently, so the mirror can land a
// millisecond before its source, and the next page load would then copy over it.
// Byte-identical today, so nothing moved — but the day the two manifest entries
// legitimately differ, opening the review page would silently overwrite one
// with the other and banner the result as a figure that exists only on this
// machine, which the reviewer never touched.
export function syncJbrowseImgMirror(name: string) {
  if (!name.startsWith(jbrowseImgPrefix)) {
    return
  }
  // the `jbrowse-img/` segment names the mirror directory under static/img; on
  // the source side it is already the directory being resolved against
  const src = path.resolve(
    jbrowseImgSrcDir,
    `${name.slice(jbrowseImgPrefix.length)}.png`,
  )
  const dest = path.resolve(imgDir, `${name}.png`)
  if (
    !src.startsWith(jbrowseImgSrcDir + path.sep) ||
    !dest.startsWith(imgDir + path.sep) ||
    !fs.existsSync(src)
  ) {
    return
  }
  if (!fs.existsSync(dest)) {
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.copyFileSync(src, dest)
    return
  }
  // Reading both is the point, but only for a pair the cheap check already
  // flagged: an unchanged mirror costs two stats, not two megabytes.
  if (
    fs.statSync(dest).mtimeMs < fs.statSync(src).mtimeMs &&
    !fs.readFileSync(dest).equals(fs.readFileSync(src))
  ) {
    fs.copyFileSync(src, dest)
  }
}

// The same sync over the whole mirror, ahead of a scan rather than per name.
// The scan hashes every figure on disk in one pass, so a jb2export that arrives
// after that pass would be hashed as the stale mirror and served as the fresh
// one — a card whose `?v=` names bytes it is not showing, cached for a year.
// One readdir of a flat directory, against the 27 stat pairs the per-name form
// cost anyway.
function syncJbrowseImgMirrors() {
  let entries: string[]
  try {
    entries = fs.readdirSync(jbrowseImgSrcDir)
  } catch {
    // no jb2export renders here; nothing to mirror
    return
  }
  for (const entry of entries) {
    if (entry.endsWith('.png')) {
      syncJbrowseImgMirror(`${jbrowseImgPrefix}${entry.slice(0, -4)}`)
    }
  }
}

// sha1 of a screenshot's PNG on disk, used to keep a verdict valid only while
// the reviewed image is unchanged (see isVerdictStale). The mirror sync happens
// here rather than only when the image is served: a hash taken before the sync
// describes bytes the reviewer will never see, and the write that carries it as
// a precondition then fails as a conflict against the figure it just looked at.
//
// Deliberately not the sha256 the figure store keys on, and deliberately not
// memoized: this is the precondition the verdict routes check inside their lock,
// so it has to read what is on disk at that instant. The store hashes below
// answer a different question — what moved against a baseline — and are scanned
// in bulk.
export function imageHash(name: string): string | undefined {
  syncJbrowseImgMirror(name)
  return hashFile(path.join(imgDir, `${name}.png`))
}

// ---------------------------------------------------------------------------
// the baseline a review is against
// ---------------------------------------------------------------------------

// Figure BYTES are gitignored — they live in the S3 store and git tracks
// `figures.lock` (figure-store.ts explains why). So the baseline is that file at
// origin/main, NOT the tree: `git ls-tree`/`git diff` over website/static/img
// now match nothing, which read as "every figure is new and none has changed" on
// all ~450 cards at once, with the whole origin/main column saying "not on
// origin/main".
//
// The store pays this back with more than it took. A baseline line carries the
// sha256, which IS the store key, so the before-picture is a public immutable
// URL the page can point an <img> straight at — no `git show` per image, and the
// link keeps working from any commit's manifest.
const baseRef = 'origin/main'

// What the review is being compared against, for the banner.
//
// `found: false` is the case worth saying out loud: no figures.lock at that ref
// means no baseline, and every figure then reads "new" on every card at once —
// precisely the symptom this file was just rewritten to fix, reachable again
// through a fork with no `origin`, a shallow clone, or a ref that was never
// fetched. An empty baseline cannot be told apart from a branch that genuinely
// added everything, so the page has to be told which it is.
//
// `commit`/`date` are the other half. origin/main is whatever was last fetched,
// so on a machine that has not fetched in a week "changed vs main" silently
// means "changed vs a week-old main" — an assumption the reviewer is making
// either way, and one git can answer for the price of a `git log -1`.
export interface BaselineState {
  ref: string
  found: boolean
  figures: number
  commit?: string
  date?: string
}

export function getBaselineState(): BaselineState {
  const figures = getBaseline().size
  return {
    ref: baseRef,
    found: baselineFound,
    figures,
    ...describeRef(baseRef),
  }
}

let baseline: Map<string, FigureEntry> | undefined
let baselineFound = false
let onDisk: Map<string, FigureEntry> | undefined
let worktree: WorktreeState | undefined

// An empty map when there is no figures.lock at origin/main (an old ref, a fork
// with no remote, a shallow clone). Every figure then reads as added on this
// branch — the only thing a comparison against nothing can say, but NOT a fact
// about the branch, so `baselineFound` keeps the two apart for the banner. See
// getBaselineState.
function getBaseline() {
  if (!baseline) {
    const found = manifestAt(baseRef)
    baselineFound = found !== undefined
    baseline = found ?? new Map()
  }
  return baseline
}

function getOnDisk() {
  onDisk ??= describeWorktree()
  return onDisk
}

// What the figures on this disk and figures.lock disagree about: which are
// unpushed (so a verdict would be against pixels nobody else gets) and which are
// unpulled (so there is no picture to judge). Shared with the store banner —
// hashing 62 MB is the most expensive thing a page load does and it happens
// once.
export function getWorktreeState(): WorktreeState {
  worktree ??= inspectWorktree(readManifest(), getOnDisk())
  return worktree
}

// Drop every memoized scan of the working tree: the doc usage index, the
// baseline manifest, and the hashes of the figures on disk. A review session IS
// regenerate, reload, look again, so a cache held for the life of the server
// reports the tree as it was when it started — a figure regenerated an hour ago
// still reads "unchanged vs main", and a doc reference added since still reads
// "not referenced in any doc".
export function refreshWorkingTreeScans() {
  usageIndex = undefined
  baseline = undefined
  onDisk = undefined
  worktree = undefined
  syncJbrowseImgMirrors()
}

// Which figures the desktop generator produces, in ./desktop-figures.ts so that
// desktopFigures.test.ts can check it against that generator — this module is
// unimportable from a test, since import.meta below defeats jest's CJS
// transform. Re-exported because this is where its consumers already look.
export { desktopAutogenNames } from './desktop-figures.ts'

// The full reviewable set: every generate-screenshots spec PLUS every image a
// doc references that actually lives in static/img. The union means gallery and
// hand-captured UI-flow images get reviewed too, not just the spec-driven ones.
// A doc-referenced name with no spec and no PNG on disk is a third-party remote
// image (not ours to review) and is excluded.
//
// Blog-only figures are excluded: blog posts are historical snapshots of past
// releases, so their images aren't kept current and shouldn't surface as review
// work. A figure shared by a blog post AND a live doc (or backed by a spec)
// stays in — its non-blog usage is what makes it reviewable.
export function collectScreenshots(specs: ScreenshotSpec[]): Screenshot[] {
  const specNames = new Set(specs.map(s => s.name))
  const index = getUsageIndex()
  const disk = getOnDisk()
  const base = getBaseline()
  const unpulled = new Set(getWorktreeState().missing)
  const names = new Set(specNames)
  for (const [name, usages] of index) {
    const liveUsages = usages.filter(u => !u.file.startsWith('blog/'))
    // On disk OR named by figures.lock. The `missing` half is what keeps a
    // figure this checkout has not pulled reachable: the seven figures with no
    // spec (product_architecture, pangenome/graph, …) get in only through this
    // scan, so gating on the disk alone dropped them from the review entirely on
    // an unpulled checkout — while the banner above the cards was promising
    // "their cards are blank until you do". The unpulled card, with `pnpm
    // figures:pull` on it, is exactly the thing that was silently absent. A
    // doc-referenced name in neither is a third-party remote image and stays out.
    if (
      liveUsages.length > 0 &&
      (disk.has(figurePath(name)) || unpulled.has(figurePath(name)))
    ) {
      names.add(name)
    }
  }
  for (const name of desktopAutogenNames) {
    names.add(name)
  }

  const toPart = (name: string): ScreenshotPart => ({
    name,
    usages: index.get(name) ?? [],
    autogenerated: specNames.has(name) || desktopAutogenNames.has(name),
    ...compareToBaseline(figurePath(name), disk, base, unpulled),
  })

  // A compose spec's parts are half-figures: the published image is the stack,
  // and no doc ever writes `/img/<part>.png` (it reaches each state through
  // `<Figure links=...>`). Listing them alongside the stack asks a reviewer to
  // judge the same pixels three times and flags each part "not referenced in any
  // doc". Fold them into the parent instead — a part that a doc DOES reference
  // directly stays a figure of its own, so folding can never hide one.
  const partsOf = new Map(
    specs.flatMap(spec =>
      spec.mode === 'compose' ? [[spec.name, spec.parts] as const] : [],
    ),
  )
  const foldedParts = new Set(
    [...partsOf.values()].flatMap(parts =>
      parts.filter(part => !index.has(part)),
    ),
  )

  return [...names]
    .filter(name => !foldedParts.has(name))
    .sort((a, b) => a.localeCompare(b))
    .map(name => ({
      ...toPart(name),
      // every part, including one that kept its own card because a doc
      // references it directly. The parent lists what it is stacked from, and
      // "a part moved but the stack didn't" is only answerable if the list is
      // the whole recipe.
      parts: (partsOf.get(name) ?? []).map(toPart),
    }))
}

export function loadReport(): Record<string, Verdict> {
  return loadReportFile(reportPath)
}

export function saveReport(report: Record<string, Verdict>) {
  saveReportFile(reportPath, report)
}

// Read-modify-write under a cross-process lock. Every writer of a verdict goes
// through this rather than loadReport/saveReport, which are for readers and for
// whole-report rewrites respectively.
export function updateReport<T>(
  mutate: (report: Record<string, Verdict>) => T,
): T {
  return updateReportFile(reportPath, mutate)
}
