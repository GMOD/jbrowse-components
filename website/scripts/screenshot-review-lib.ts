const __dirname = path.dirname(fileURLToPath(import.meta.url))

export const websiteRoot = path.resolve(__dirname, '..')
export const imgDir = path.resolve(websiteRoot, 'static', 'img')
export const reportPath = path.resolve(__dirname, 'screenshot-review.json')

// Directories scanned for doc usages of each image
const docRoots = ['docs', 'blog', 'src/pages'].map(d =>
  path.resolve(websiteRoot, d),
)

export interface DocUsage {
  file: string // relative to websiteRoot
  line: number
  caption: string // Figure caption / markdown alt text
}

// One PNG's review state — a whole figure, or one part of a composed figure.
// `autogenerated` means a generator (a generate-screenshots.ts spec, or a
// desktop capture) can reproduce it; otherwise it's a hand-captured image kept
// only in static/img (e.g. UI-flow walkthroughs, the gallery read-vs-ref shot)
// that must be re-captured by hand.
export interface ScreenshotPart {
  name: string
  usages: DocUsage[]
  autogenerated: boolean
  exists: boolean
  existsOnMain: boolean
  // present on both this branch and origin/main but the working-tree pixels
  // differ — i.e. an update the current work introduced
  changed: boolean
}

export interface Screenshot extends ScreenshotPart {
  // for a compose figure, the part specs stacked into it; empty for every other
  // figure. Parts are ingredients rather than reviewable figures of their own,
  // so they appear here instead of as entries in their own right.
  parts: ScreenshotPart[]
}

function walkMarkdown(dir: string): string[] {
  const out: string[] = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      out.push(...walkMarkdown(full))
    } else if (/\.mdx?$/.test(entry.name)) {
      out.push(full)
    }
  }
  return out
}

function findMarkdownFiles() {
  return docRoots.filter(d => fs.existsSync(d)).flatMap(d => walkMarkdown(d))
}

// gallery.ts is the single source of truth for /gallery/ (see
// website/CLAUDE.md); its items reference images via `spec`/`img` fields, not
// literal "/img/<name>.png" text, so it needs its own scan rather than being
// added to docRoots.
const galleryFile = path.resolve(websiteRoot, 'src/lib/gallery.ts')

// Pull the caption="..." attribute out of a <Figure .../> line if present
function extractFigureCaption(line: string) {
  const m = /caption=("|')([\s\S]*?)\1/.exec(line)
  return m?.[2] ?? ''
}

// Pull the alt text out of a markdown image ![alt](src)
function extractMarkdownAlt(line: string) {
  const m = /!\[([^\]]*)\]/.exec(line)
  return m?.[1] ?? ''
}

// Every image-name a single line references. Matches the `/img/<name>.png`
// segment in any form the docs use — <Figure src="/img/x.png"/>,
// ![alt](/jb2/img/x.png), and absolute github-raw URLs that point back at this
// repo's website/static/img/x.png (used in blog posts so external aggregators
// resolve the image). Third-party github-raw images (jb2export, plugin-list)
// also match here but get dropped later because their PNG isn't on disk.
function imageNamesOnLine(line: string): string[] {
  const names: string[] = []
  const re = /\/img\/([A-Za-z0-9_/-]+)\.png/g
  let m: RegExpExecArray | null = re.exec(line)
  while (m) {
    names.push(m[1]!)
    m = re.exec(line)
  }
  return names
}

// Mirrors gallery.ts's itemImg(): an item's figure is its explicit `img`
// (".png" stripped), else its `spec` name. Field order in each object literal
// isn't guaranteed, so scan the whole item text rather than assuming img/spec
// comes after label.
function galleryItemImageName(itemText: string): string | undefined {
  const img = /\bimg:\s*(['"])([^'"]+)\1/.exec(itemText)
  if (img) {
    return img[2]!.replace(/\.png$/, '')
  }
  const spec = /\bspec:\s*(['"])([^'"]+)\1/.exec(itemText)
  return spec?.[2]
}

// gallery.ts has no markup to walk line-by-line; instead split on each
// object literal `{ ... }` in the `items:` arrays and pull `label`/`img`/`spec`
// out of each. Good enough for gallery.ts's own flat, unnested item shape.
function scanGalleryUsages(): Map<string, DocUsage[]> {
  const index = new Map<string, DocUsage[]>()
  if (!fs.existsSync(galleryFile)) {
    return index
  }
  const rel = path.relative(websiteRoot, galleryFile)
  const text = fs.readFileSync(galleryFile, 'utf8')
  const lines = text.split('\n')
  let itemStart = -1
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!
    if (/^\s*\{$/.test(line)) {
      itemStart = i
    } else if (/^\s*\},?$/.test(line) && itemStart >= 0) {
      const itemLines = lines.slice(itemStart, i + 1)
      const itemText = itemLines.join('\n')
      const name = galleryItemImageName(itemText)
      if (name) {
        const label = /\blabel:\s*(['"])([^'"]*)\1/.exec(itemText)?.[2] ?? ''
        const usage: DocUsage = {
          file: rel,
          line: itemStart + 1,
          caption: label,
        }
        const list = index.get(name)
        if (list) {
          list.push(usage)
        } else {
          index.set(name, [usage])
        }
      }
      itemStart = -1
    }
  }
  return index
}

// Scan every markdown file once, building name -> usages. Re-reading per-name
// would be O(names × files); this is O(files).
function buildUsageIndex(): Map<string, DocUsage[]> {
  const index = scanGalleryUsages()
  for (const file of findMarkdownFiles()) {
    // a doc file can be deleted/regenerated between the directory walk and now
    // (e.g. autogen rewriting docs/config/*.md); a vanished file is just not a
    // usage, so skip it rather than crashing
    const text = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
    if (!text.includes('/img/')) {
      continue
    }
    const lines = text.split('\n')
    const rel = path.relative(websiteRoot, file)
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i]!
      const names = imageNamesOnLine(line)
      if (names.length > 0) {
        const isFigure = line.includes('<Figure')
        const usage: DocUsage = {
          file: rel,
          line: i + 1,
          caption: isFigure
            ? extractFigureCaption(line)
            : extractMarkdownAlt(line),
        }
        for (const name of names) {
          const list = index.get(name)
          if (list) {
            list.push(usage)
          } else {
            index.set(name, [usage])
          }
        }
      }
    }
  }
  return index
}

let usageIndex: Map<string, DocUsage[]> | undefined

function getUsageIndex() {
  if (!usageIndex) {
    usageIndex = buildUsageIndex()
  }
  return usageIndex
}

// jb2export writes its renders to products/jbrowse-img/img (the README/npm
// copy); the website mirror at static/img/jbrowse-img is only refreshed by a
// `pnpm screenshots` (captureCliSpec) or `pnpm autogen` run. So a fresh
// jb2export the reviewer just produced can leave the review tooling looking at
// the stale mirror. Self-heal on read: if the source render is newer than (or
// absent from) the mirror, copy it over before anyone hashes or serves it.
const jbrowseImgPrefix = 'jbrowse-img/'
const jbrowseImgSrcDir = path.resolve(
  websiteRoot,
  '..',
  'products',
  'jbrowse-img',
  'img',
)

// Called on every read of a mirrored figure rather than once at startup: the
// hash and the bytes a reviewer is served have to agree, and a jb2export run
// mid-session is exactly the case this exists for. Two stats when there is
// nothing to do.
export function syncJbrowseImgMirror(name: string) {
  if (!name.startsWith(jbrowseImgPrefix)) {
    return
  }
  // the `jbrowse-img/` segment names the mirror directory under static/img; on
  // the source side it is already the directory being resolved against
  const src = path.resolve(
    jbrowseImgSrcDir,
    `${name.slice(jbrowseImgPrefix.length)}.png`,
  )
  const dest = path.resolve(imgDir, `${name}.png`)
  if (
    !src.startsWith(jbrowseImgSrcDir + path.sep) ||
    !dest.startsWith(imgDir + path.sep) ||
    !fs.existsSync(src)
  ) {
    return
  }
  const srcMtime = fs.statSync(src).mtimeMs
  if (!fs.existsSync(dest) || fs.statSync(dest).mtimeMs < srcMtime) {
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.copyFileSync(src, dest)
  }
}

function pngExists(name: string) {
  syncJbrowseImgMirror(name)
  return fs.existsSync(path.join(imgDir, `${name}.png`))
}

// sha1 of a screenshot's committed PNG, used to keep a verdict valid only while
// the reviewed image is unchanged (see isVerdictStale). The mirror sync happens
// here rather than only when the image is served: a hash taken before the sync
// describes bytes the reviewer will never see, and the write that carries it as
// a precondition then fails as a conflict against the figure it just looked at.
export function imageHash(name: string): string | undefined {
  syncJbrowseImgMirror(name)
  return hashFile(path.join(imgDir, `${name}.png`))
}

const repoRoot = path.resolve(websiteRoot, '..')

// git paths are always repo-root-relative, unlike imgDir (an absolute path
// that already accounts for where this script happens to be run from).
const imgGitPrefix = 'website/static/img/'

function gitPathToName(gitPath: string): string {
  return gitPath.replace(imgGitPrefix, '').replace(/\.png$/, '')
}

// execFileSync's default maxBuffer (1MB) is close enough to real screenshot
// sizes (some committed PNGs already exceed 900KB) that git output can get cut
// off; raise it well past what any single screenshot or file listing needs.
const gitMaxBuffer = 1024 * 1024 * 50

// Cache of which names exist on origin/main.
let mainSet: Set<string> | undefined

function getMainSet(): Set<string> {
  if (!mainSet) {
    try {
      const out = execFileSync(
        'git',
        ['ls-tree', '--name-only', '-r', 'origin/main', imgGitPrefix],
        { cwd: repoRoot, encoding: 'utf8', maxBuffer: gitMaxBuffer },
      )
      mainSet = new Set(
        out.trim().split('\n').filter(Boolean).map(gitPathToName),
      )
    } catch {
      mainSet = new Set()
    }
  }
  return mainSet
}

export function mainPngExists(name: string): boolean {
  return getMainSet().has(name)
}

// Names whose working-tree PNG differs from origin/main. `git diff` compares by
// blob hash, so this is exact and decode-free; it also picks up both committed
// branch edits and uncommitted regens. Untracked (brand-new) files don't appear
// here — those are the "new" set instead (existsOnMain === false).
let changedSet: Set<string> | undefined

function getChangedSet(): Set<string> {
  if (!changedSet) {
    try {
      const out = execFileSync(
        'git',
        ['diff', '--name-only', 'origin/main', '--', imgGitPrefix],
        { cwd: repoRoot, encoding: 'utf8', maxBuffer: gitMaxBuffer },
      )
      changedSet = new Set(
        out.trim().split('\n').filter(Boolean).map(gitPathToName),
      )
    } catch {
      changedSet = new Set()
    }
  }
  return changedSet
}

export function mainPngChanged(name: string): boolean {
  return getChangedSet().has(name)
}

// Drop every memoized scan of the working tree: the doc usage index and both
// git sets. A review session IS regenerate, reload, look again, so a cache held
// for the life of the server reports the tree as it was when it started — a
// figure regenerated an hour ago still reads "unchanged vs main", and a doc
// reference added since still reads "not referenced in any doc". The next read
// re-scans (~190ms, against the ~200ms the same response already spends hashing
// every PNG).
export function refreshWorkingTreeScans() {
  usageIndex = undefined
  mainSet = undefined
  changedSet = undefined
}

export function readMainPng(name: string): Buffer | undefined {
  const gitPath = `${imgGitPrefix}${name}.png`
  try {
    return execFileSync('git', ['show', `origin/main:${gitPath}`], {
      cwd: repoRoot,
      maxBuffer: gitMaxBuffer,
    })
  } catch {
    return undefined
  }
}

// Desktop screenshots are produced by a SEPARATE generator
// (products/jbrowse-desktop/test/screenshots.ts, a Selenium + Electron run)
// rather than generate-screenshots.ts. They have no web spec, so without this
// list the reviewer mis-classifies them as hand-captured ("manual"). Keep this
// in sync with that file's FIGURES list (its capture() calls and its PROCEDURES
// table, whose stacked step figures are committed the same way).
export const desktopAutogenNames = new Set([
  'desktop-landing',
  'desktop-available-genomes',
  'desktop-open-genome-steps',
  'desktop-available-genomes-steps',
  'desktop-add-track-steps',
  'desktop-cli-config',
  'desktop-blat-search',
  'desktop-blat-results',
  'desktop-ispcr',
  'desktop-ispcr-results',
])

// The full reviewable set: every generate-screenshots spec PLUS every image a
// doc references that actually lives in static/img. The union means gallery and
// hand-captured UI-flow images get reviewed too, not just the spec-driven ones.
// A doc-referenced name with no spec and no PNG on disk is a third-party remote
// image (not ours to review) and is excluded.
//
// Blog-only figures are excluded: blog posts are historical snapshots of past
// releases, so their images aren't kept current and shouldn't surface as review
// work. A figure shared by a blog post AND a live doc (or backed by a spec)
// stays in — its non-blog usage is what makes it reviewable.
export function collectScreenshots(specs: ScreenshotSpec[]): Screenshot[] {
  const specNames = new Set(specs.map(s => s.name))
  const index = getUsageIndex()
  const names = new Set(specNames)
  for (const [name, usages] of index) {
    const liveUsages = usages.filter(u => !u.file.startsWith('blog/'))
    if (liveUsages.length > 0 && pngExists(name)) {
      names.add(name)
    }
  }
  for (const name of desktopAutogenNames) {
    names.add(name)
  }

  const toPart = (name: string): ScreenshotPart => ({
    name,
    usages: index.get(name) ?? [],
    autogenerated: specNames.has(name) || desktopAutogenNames.has(name),
    exists: pngExists(name),
    existsOnMain: mainPngExists(name),
    changed: pngExists(name) && mainPngChanged(name),
  })

  // A compose spec's parts are half-figures: the published image is the stack,
  // and no doc ever writes `/img/<part>.png` (it reaches each state through
  // `<Figure links=...>`). Listing them alongside the stack asks a reviewer to
  // judge the same pixels three times and flags each part "not referenced in any
  // doc". Fold them into the parent instead — a part that a doc DOES reference
  // directly stays a figure of its own, so folding can never hide one.
  const partsOf = new Map(
    specs.flatMap(spec =>
      spec.mode === 'compose' ? [[spec.name, spec.parts] as const] : [],
    ),
  )
  const foldedParts = new Set(
    [...partsOf.values()].flatMap(parts =>
      parts.filter(part => !index.has(part)),
    ),
  )

  return [...names]
    .filter(name => !foldedParts.has(name))
    .sort((a, b) => a.localeCompare(b))
    .map(name => ({
      ...toPart(name),
      // every part, including one that kept its own card because a doc
      // references it directly. The parent lists what it is stacked from, and
      // "a part moved but the stack didn't" is only answerable if the list is
      // the whole recipe.
      parts: (partsOf.get(name) ?? []).map(toPart),
    }))
}

export function loadReport(): Record<string, Verdict> {
  return loadReportFile(reportPath)
}

export function saveReport(report: Record<string, Verdict>) {
  saveReportFile(reportPath, report)
}

// Read-modify-write under a cross-process lock. Every writer of a verdict goes
// through this rather than loadReport/saveReport, which are for readers and for
// whole-report rewrites respectively.
export function updateReport<T>(
  mutate: (report: Record<string, Verdict>) => T,
): T {
  return updateReportFile(reportPath, mutate)
}
