import { FIT_LADDER } from '../../../plugins/features/src/LinearBasicDisplay/fitLadderOrder.ts'
import { rewriteMarkerBlock } from '../markerDocs.ts'
import { readDoc, writeUnformatted } from './format.ts'
import { markdownTable, tableCell } from './markdown.ts'

import type { FitLevel } from '../../../plugins/features/src/LinearBasicDisplay/fitLadderOrder.ts'

const SOURCE = 'plugins/features/src/LinearBasicDisplay/fitLadderOrder.ts'
const DIAGRAM = 'agent-docs/reference/diagrams/feature-budget.dot'
const LABEL_WIDTH = 42

const RUNG_DOES: Record<FitLevel, string> = {
  full: 'names and descriptions',
  labels: 'descriptions dropped',
  isoforms:
    'each gene trimmed to the largest transcripts-per-gene whose NAMED pack fits, found by bisection — names before isoforms; skipped under geneGlyphMode all',
  thinned:
    'every name kept, bodies shortened to the largest scale that fits, down to 0.4x the label font — names before height',
  decimated:
    'a name only where it is isolated, the factor solved with bodies at that floor, or at the squeeze floor where no name survives it; then bodies grow back into the freed room',
  bodies: 'no names or descriptions',
  bare: 'subfeature labels dropped too; a rung only where below label rows are reserved',
}

function wrapped(text: string) {
  return text
    .split(' ')
    .reduce<string[]>(
      (lines, word) =>
        lines.length && `${lines.at(-1)} ${word}`.length <= LABEL_WIDTH
          ? [...lines.slice(0, -1), `${lines.at(-1)} ${word}`]
          : [...lines, word],
      [],
    )
    .join('\\n')
}

function diagramChain() {
  const width = Math.max(...FIT_LADDER.map(level => level.length))
  return [
    `// Generated by \`pnpm autogen\` from FIT_LADDER in ${SOURCE}; edit that, not this block.`,
    `ladder -> ${FIT_LADDER.join(' -> ')}`,
    ...FIT_LADDER.map(
      level =>
        `${level.padEnd(width)} [label="${wrapped(`${level}: ${RUNG_DOES[level]}`)}"]`,
    ),
    FIT_LADDER.map(level => `${level} -> scale`).join('  '),
  ].map(line => `  ${line}`)
}

function spliceDiagram() {
  const lines = readDoc(DIAGRAM).split('\n')
  const marker = (edge: string) =>
    lines.findIndex(line => line.trim() === `// ${edge} GENERATED FIT_LADDER`)
  const begin = marker('BEGIN')
  const end = marker('END')
  if (begin < 0 || end < begin) {
    throw new Error(
      `${DIAGRAM}: no \`// BEGIN GENERATED FIT_LADDER\` ... \`// END GENERATED FIT_LADDER\` pair to write the rung chain into`,
    )
  }
  return writeUnformatted(
    DIAGRAM,
    [...lines.slice(0, begin + 1), ...diagramChain(), ...lines.slice(end)].join(
      '\n',
    ),
  )
}

export function writeFitLadderDocs() {
  return [
    ...rewriteMarkerBlock(
      'FIT_LADDER',
      markdownTable(
        ['rung, tried in order', 'what it lays out'],
        FIT_LADDER.map(
          level => `| \`${level}\` | ${tableCell(RUNG_DOES[level])} |`,
        ),
      ),
    ),
    ...spliceDiagram(),
  ]
}
