import { readDoc, writeDoc, writtenDocs } from './format.ts'
import { configManifestTables } from './generateConfigDocs.ts'

// The jbrowse-authoring skill's index of every registered type: the manifest's
// type tables, each name linked to the config page this run wrote for it.
// Written here rather than by generateConfigManifest.ts, which runs before the
// pages exist and so linked against the previous run's set.
const INDEX = '.claude/skills/jbrowse-authoring/references/config-types.md'
const CONFIG_DIR = 'website/docs/config/'

export function writeConfigTypeIndex() {
  const schema = configManifestTables()
  const pages = writtenDocs().filter(
    f => f.startsWith(CONFIG_DIR) && f.endsWith('.md'),
  )
  const slugOf = (file: string) =>
    file.slice(CONFIG_DIR.length).replace(/\.md$/, '')
  const documented = new Set(pages.map(f => slugOf(f).toLowerCase()))

  // A display taking its schema from a shared one (the multi-sample variant
  // displays from SharedVariantDisplay) is documented on the Shared* page that
  // names it.
  const sharedPageFor = new Map<string, string>()
  for (const file of pages.filter(f => slugOf(f).startsWith('Shared'))) {
    const body = readDoc(file)
    for (const group of ['tracks', 'displays', 'adapters']) {
      for (const name of Object.keys(schema[group] ?? {})) {
        if (!documented.has(name.toLowerCase()) && body.includes(name)) {
          sharedPageFor.set(name, slugOf(file))
        }
      }
    }
  }

  const pageUrl = (slug: string) =>
    `https://jbrowse.org/jb2/docs/config/${slug.toLowerCase()}.md`
  const link = (name: string) => {
    if (documented.has(name.toLowerCase())) {
      return `[${name}](${pageUrl(name)})`
    }
    const shared = sharedPageFor.get(name)
    return shared
      ? `${name} — slots documented under [${shared}](${pageUrl(shared)})`
      : `${name} (no docs page)`
  }
  const names = (group: string) => Object.keys(schema[group] ?? {})

  const lines = [
    '<!-- Generated by website/scripts/api-docs/generateConfigTypeIndex.ts. Do not edit by hand. -->',
    '',
    '# JBrowse config types',
    '',
    'Every type the core plugins register. For the slots a type accepts, fetch',
    'its page — the URL pattern is `https://jbrowse.org/jb2/docs/config/<lowercased type name>.md`.',
    '',
    'A type not listed here is not necessarily wrong: plugins register their own.',
    '',
    '## Track types',
    '',
    'A track pairs one adapter (where the data is) with one or more displays (how it is drawn).',
    'The shortest track is `{ "trackId", "uri", "assemblyNames" }`, and in a',
    'config declaring one assembly the last of those goes too: the type and',
    "adapter come from the file's extension, and any key written beside `uri`",
    'overrides the inference.',
    '',
    ...Object.entries(schema.tracks ?? {}).map(
      ([name, entry]) =>
        `- ${link(name)} — displays: ${(entry.displayTypes ?? []).join(', ') || 'none'}`,
    ),
    '',
    '## Display types',
    '',
    ...names('displays').map(name => `- ${link(name)}`),
    '',
    '## Adapter types',
    '',
    'Adapters marked `uri` accept the `uri` shorthand (`{type, uri}`) instead of',
    'the explicit location slot, and derive the index location from it.',
    '',
    ...Object.entries(schema.adapters ?? {}).map(([name, entry]) => {
      const shorthands = entry.shorthandKeys ?? []
      const suffix = shorthands.length
        ? ` — shorthands: ${shorthands.join(', ')}`
        : ''
      return `- ${link(name)}${suffix}`
    }),
    '',
    '## Text search adapters',
    '',
    ...names('textSearchAdapters').map(name => `- ${link(name)}`),
    '',
    '## Connection types',
    '',
    ...names('connections').map(name => `- ${link(name)}`),
    '',
  ]
  writeDoc(INDEX, `${lines.join('\n')}\n`)
}
