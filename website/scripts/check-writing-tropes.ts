// Ratchets per-doc counts of the writing tropes a grep can find reliably in the
// hand-written docs: "which is what"/"is what makes" clefts, and "silently" or
// "quietly" standing in for the mechanism. The checklist behind them is
// github.com/cmdcolin/claudish (anti-ai-writing-tropes). Generated pages, code
// fences and marker blocks are skipped; those tropes are fixed at the JSDoc.
//
// Run `pnpm check-writing-tropes` to rewrite the list.
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { check, checkOrWrite, docFiles } from './check-utils.ts'
import { docRelative, docsDir } from './paths.ts'

const listFile = join(import.meta.dirname, 'writing-tropes.txt')

const GENERATED_PREFIXES = [
  'config/',
  'models/',
  'api/',
  'cli.md',
  'jbrowse-img.md',
  'jbrowse-capture.md',
]

const tropeRe =
  /\bwhich is what\b|\bis what (?:makes|keeps|lets|stops|turns|decides|gives|picks)\b|\bsilently\b|\bquietly\b/gi

const HEADER = `# AUTO-GENERATED by scripts/check-writing-tropes.ts — do not edit by hand.
# Per-doc count of "which is what"-style clefts and "silently"/"quietly", as
# "<doc> <count>". Regenerate with \`pnpm check-writing-tropes\`.
#
# A higher count is a regression: write the plain verb, or say what happens
# instead of "silently".
`

function proseLines(text: string) {
  let inFence = false
  let inMarker = false
  return text.split('\n').filter(line => {
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence
      return false
    }
    if (/<!-- [^>]*\bSTART\b/.test(line) || line.includes('BEGIN GENERATED')) {
      inMarker = true
    }
    if (/<!-- [^>]*\bEND\b/.test(line) || line.includes('END GENERATED')) {
      inMarker = false
      return false
    }
    return !inFence && !inMarker
  })
}

const counts = new Map<string, number>()
for (const file of docFiles(docsDir)) {
  const rel = docRelative(file)
  if (GENERATED_PREFIXES.some(p => rel.startsWith(p))) {
    continue
  }
  const n = proseLines(readFileSync(file, 'utf8')).reduce(
    (sum, line) => sum + (line.match(tropeRe)?.length ?? 0),
    0,
  )
  if (n > 0) {
    counts.set(rel, n)
  }
}
const entries = [...counts].sort(([a], [b]) => a.localeCompare(b))
const content = `${HEADER}${entries.map(([doc, n]) => `${doc} ${n}`).join('\n')}\n`

if (check) {
  const committed = new Map(
    readFileSync(listFile, 'utf8')
      .split('\n')
      .filter(l => l && !l.startsWith('#'))
      .map(l => {
        const [doc, n] = l.split(' ')
        return [doc!, Number(n)] as const
      }),
  )
  const grew = entries.filter(([doc, n]) => n > (committed.get(doc) ?? 0))
  if (grew.length > 0) {
    console.error(
      `${grew.length} doc(s) gained a writing trope:\n${grew
        .map(([doc, n]) => `  ${doc}: ${committed.get(doc) ?? 0} → ${n}`)
        .join(
          '\n',
        )}\n\nLines matching ${tropeRe} — rewrite them with the plain ` +
        `verb, or say what happens in place of "silently".`,
    )
    process.exit(1)
  }
}

checkOrWrite({
  path: listFile,
  content,
  label: `writing-tropes.txt (${entries.reduce((s, [, n]) => s + n, 0)} across ${entries.length} docs)`,
  staleHint: 'run `pnpm check-writing-tropes` to hold the gain',
})
