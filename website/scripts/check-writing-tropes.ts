// Ratchets per-doc counts of the writing tropes a grep can find reliably in the
// hand-written docs: "which is what"/"is what makes" clefts, and "silently" or
// "quietly" standing in for the mechanism. The checklist behind them is
// github.com/cmdcolin/claudish (anti-ai-writing-tropes). Generated pages, code
// fences and marker blocks are skipped; those tropes are fixed at the JSDoc.
//
// Run `pnpm check-writing-tropes` to rewrite the list.
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { checkOrWrite, docFiles, ratchetDocCounts } from './check-utils.ts'
import { fencedLines } from './docFenceRegions.ts'
import { withoutMarkerBlocks } from './markerBlocks.ts'
import { docRelative, docsDir } from './paths.ts'

const listFile = join(import.meta.dirname, 'writing-tropes.txt')

const GENERATED_PREFIXES = [
  'config/',
  'models/',
  'api/',
  'cli.md',
  'jbrowse-img.md',
  'jbrowse-capture.md',
  'user_guide.md',
  'config_guide.md',
  'developer_guide.md',
]

const tropeRe =
  /\bwhich is what\b|\bis what (?:makes|keeps|lets|stops|turns|decides|gives|picks)\b|\bsilently\b|\bquietly\b/gi

const HEADER = `# AUTO-GENERATED by scripts/check-writing-tropes.ts — do not edit by hand.
# Per-doc count of "which is what"-style clefts and "silently"/"quietly", as
# "<doc> <count>". Regenerate with \`pnpm check-writing-tropes\`.
#
# A higher count is a regression: write the plain verb, or say what happens
# instead of "silently".
`

// The 1-based line of every trope match outside a fence, one entry per match.
function tropeLines(text: string, file: string) {
  const lines = withoutMarkerBlocks(text, file).split('\n')
  const fenced = fencedLines(lines)
  return lines.flatMap((line, i) =>
    fenced[i] ? [] : (line.match(tropeRe) ?? []).map(() => i + 1),
  )
}

const hits = new Map(
  docFiles(docsDir)
    .filter(
      file => !GENERATED_PREFIXES.some(p => docRelative(file).startsWith(p)),
    )
    .map(file => [
      docRelative(file),
      tropeLines(readFileSync(file, 'utf8'), file),
    ]),
)

const { content, docs, total } = ratchetDocCounts({
  hits,
  header: HEADER,
  listFile,
  regression: 'doc(s) gained a writing trope',
  describe: lines => ` (lines ${lines.join(', ')})`,
  advice: `Lines matching ${tropeRe} — rewrite them with the plain verb, or say what happens in place of "silently".`,
})

checkOrWrite({
  path: listFile,
  content,
  label: `writing-tropes.txt (${total} across ${docs} docs)`,
  staleHint: 'run `pnpm check-writing-tropes` to hold the gain',
})
