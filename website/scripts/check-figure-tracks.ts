// Ratchets, per tutorial, the tracks its figures open that the page never
// names: `figure-tracks.ts` says what counts.
//
// `--network` refreshes figure-track-names.json, the names of the remote
// configs' tracks, which the offline run needs to recognise a track a page
// names by its menu label. `--list` prints each unnamed track with its line.
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { check, checkOrWriteAll, docFiles, isFile } from './check-utils.ts'
import {
  figureTracks,
  prerequisiteTutorials,
  isRemote,
  namesFile,
  unnamedFigureTracks,
} from './figure-tracks.ts'
import { docRelative, docsDir } from './paths.ts'

import type { TrackNames, UnnamedTrack } from './figure-tracks.ts'

const listFile = join(import.meta.dirname, 'figure-tracks.txt')
const list = process.argv.includes('--list')
const network = process.argv.includes('--network')

const HEADER = `# AUTO-GENERATED by scripts/check-figure-tracks.ts — do not edit by hand.
# Per-tutorial count of tracks a figure opens that the page never names by id
# or by name, as "<doc> <count>". Regenerate with \`pnpm check-figure-tracks\`.
#
# A higher count is a regression: a reader on their own instance cannot get a
# picture whose tracks the page never sets up. Give the track a fence, or name
# the menu label that adds it.
`

const files = docFiles(join(docsDir, 'tutorials')).filter(
  f => !f.endsWith('CLAUDE.md'),
)
const texts = new Map(files.map(f => [docRelative(f), readFileSync(f, 'utf8')]))

const recorded: TrackNames = isFile(namesFile)
  ? JSON.parse(readFileSync(namesFile, 'utf8'))
  : {}

async function fetchNames() {
  const wanted = new Map<string, Set<string>>()
  for (const text of texts.values()) {
    for (const { config, trackIds } of figureTracks(text)) {
      if (isRemote(config)) {
        const ids = wanted.get(config) ?? new Set()
        trackIds.forEach(id => ids.add(id))
        wanted.set(config, ids)
      }
    }
  }
  const names: TrackNames = {}
  for (const [config, ids] of [...wanted].sort(([a], [b]) =>
    a.localeCompare(b, 'en'),
  )) {
    const res = await fetch(config)
    if (!res.ok) {
      console.error(`${config}: HTTP ${res.status}`)
      process.exit(1)
    }
    const tracks = (
      (await res.json()) as {
        tracks?: { trackId: string; name?: string }[]
      }
    ).tracks
    const byId = new Map((tracks ?? []).map(t => [t.trackId, t.name]))
    names[config] = Object.fromEntries(
      [...ids]
        .sort((a, b) => a.localeCompare(b, 'en'))
        .flatMap(id => {
          const name = byId.get(id)
          return name ? [[id, name]] : []
        }),
    )
  }
  return names
}

const names = network ? await fetchNames() : recorded

const detail = new Map<string, UnnamedTrack[]>()
for (const [doc, text] of texts) {
  const context = prerequisiteTutorials(text).flatMap(slug => {
    const prereq = texts.get(`tutorials/${slug}.md`)
    return prereq ? [prereq] : []
  })
  const hits = unnamedFigureTracks(text, names, context)
  if (hits.length > 0) {
    detail.set(doc, hits)
  }
}

if (list) {
  for (const [doc, hits] of detail) {
    for (const h of hits) {
      console.log(
        `${doc}:${h.line}: ${h.figure} opens ${h.trackId}${h.name ? ` ("${h.name}")` : ''}`,
      )
    }
  }
  process.exit(0)
}

const entries = [...detail]
  .map(([doc, hits]) => [doc, hits.length] as const)
  .sort(([a], [b]) => a.localeCompare(b, 'en'))
const content = `${HEADER}${entries.map(([doc, n]) => `${doc} ${n}`).join('\n')}\n`

if (check) {
  const committed = new Map(
    readFileSync(listFile, 'utf8')
      .split('\n')
      .filter(l => l && !l.startsWith('#'))
      .map(l => {
        const [doc, n] = l.split(' ')
        return [doc!, Number(n)] as const
      }),
  )
  const grew = entries.filter(([doc, n]) => n > (committed.get(doc) ?? 0))
  if (grew.length > 0) {
    console.error(
      `${grew.length} tutorial(s) gained a figure track the page never names:\n${grew
        .map(
          ([doc, n]) =>
            `  ${doc}: ${committed.get(doc) ?? 0} → ${n} (${detail
              .get(doc)!
              .map(h => `${h.line} ${h.trackId}`)
              .join(', ')})`,
        )
        .join(
          '\n',
        )}\n\nGive the track a fence on the page, or name the menu label that adds it.`,
    )
    process.exit(1)
  }
}

const total = entries.reduce((s, [, n]) => s + n, 0)
checkOrWriteAll(
  [
    {
      path: listFile,
      content,
      label: `figure-tracks.txt (${total} across ${entries.length} tutorials)`,
    },
    {
      path: namesFile,
      content: `${JSON.stringify(names, null, 2)}\n`,
      label: 'figure-track-names.json',
    },
  ],
  'run `pnpm check-figure-tracks --network` to record them',
)
