// The one spelling of a generated doc block, and the one reader and the one
// splice of it:
//
//   <!-- BEGIN GENERATED NAME -->            <!-- BEGIN GENERATED NAME group -->
//   …generated…                              …generated…
//   <!-- END GENERATED NAME -->              <!-- END GENERATED NAME group -->
//
// A grouped block names which of its generator's tables it renders
// (`COLOR_TABLE alignments-indicators`, `MEASUREMENT bgzf-pool-tabix`), so one
// generator feeds many blocks across many docs.
//
// A marker is one whole line, outside any code fence. Prose quoting one in
// backticks is not a block, nor is a fence quoting the convention: both are a
// doc about a block, and splicing there would rewrite the example.
import { resolve } from 'node:path'

import { docsDir, repoRoot } from './paths.ts'

const MARKER = /^<!-- (BEGIN|END) GENERATED ([A-Z][A-Z0-9_]*)(?: (\S+))? -->$/
const FENCE = /^\s*(`{3,}|~{3,})/

// Every generated block in agent-docs says so, in one line. A reader landing
// mid-file from a search hit or a deep link, where the marker comments are
// invisible, sees what looks like a hand-maintained table — which is how a
// generated table gets edited and silently overwritten on the next run.
// `isWebsiteDoc` keeps the notice out of the rendered site itself: a
// jbrowse.org visitor has no file to edit.
export const GENERATED_NOTICE =
  '_Generated by `pnpm autogen` — edit the source, not this block._'

// True for a doc under website/docs — the pages Astro renders to jbrowse.org —
// as opposed to agent-docs, which is read as source. `file` may be absolute or
// relative to `repoRoot`.
export function isWebsiteDoc(file: string) {
  return resolve(repoRoot, file).startsWith(`${docsDir}/`)
}

export function markerLine(
  edge: 'BEGIN' | 'END',
  name: string,
  group?: string,
) {
  return `<!-- ${edge} GENERATED ${group === undefined ? name : `${name} ${group}`} -->`
}

export interface MarkerBlock {
  name: string
  group: string | undefined
  // Line indices of the BEGIN and END markers.
  begin: number
  end: number
}

// Every block in a doc, in order. An unpaired or nested marker throws, since
// the block it opens is otherwise never generated while the generator reports
// the doc up to date.
export function markerBlocks(text: string, file: string) {
  const blocks: MarkerBlock[] = []
  let open: Omit<MarkerBlock, 'end'> | undefined
  let fence: string | undefined
  for (const [i, line] of text.split('\n').entries()) {
    const ticks = FENCE.exec(line)?.[1]
    if (fence !== undefined) {
      if (ticks?.startsWith(fence) && line.trim() === ticks) {
        fence = undefined
      }
    } else if (ticks !== undefined) {
      fence = ticks
    } else {
      const m = MARKER.exec(line)
      if (m) {
        const [, edge, name, group] = m
        if (edge === 'BEGIN') {
          if (open) {
            throw new Error(
              `${file}:${i + 1}: \`${line}\` opens inside ${markerLine('BEGIN', open.name, open.group)}, which has no END before it`,
            )
          }
          open = { name: name!, group, begin: i }
        } else if (
          open !== undefined &&
          open.name === name &&
          open.group === group
        ) {
          blocks.push({ ...open, end: i })
          open = undefined
        } else {
          throw new Error(
            `${file}:${i + 1}: \`${line}\` closes no open ${markerLine('BEGIN', name!, group)}`,
          )
        }
      }
    }
  }
  if (open) {
    throw new Error(
      `${file}:${open.begin + 1}: ${markerLine('BEGIN', open.name, open.group)} has no ${markerLine('END', open.name, open.group)}. The block between them is never generated, and the generator would report the doc as up to date.`,
    )
  }
  return blocks
}

// The doc with every block's lines (only `name`'s, when given), markers
// included, blanked: what a check reading a page's hand-written prose reads.
export function withoutMarkerBlocks(text: string, file: string, name?: string) {
  const lines = text.split('\n')
  for (const block of markerBlocks(text, file)) {
    if (name === undefined || block.name === name) {
      lines.fill('', block.begin, block.end + 1)
    }
  }
  return lines.join('\n')
}

// Rewrite every block named `name` (and `group`, for a grouped marker) in one
// doc with `render`'s body. A doc carrying no such block throws: the caller
// asked for a block that is not there.
//
// An empty body reads as "nothing here" while it usually means the generator's
// source parse stopped matching, so it throws unless the call says the block
// may legitimately render empty.
export function spliceMarkerBlocks({
  text,
  file,
  name,
  group,
  render,
  allowEmpty = false,
}: {
  text: string
  file: string
  name: string
  group?: string
  render: (block: MarkerBlock) => string
  allowEmpty?: boolean
}) {
  const lines = text.split('\n')
  const matching = markerBlocks(text, file).filter(
    b => b.name === name && (group === undefined || b.group === group),
  )
  if (matching.length === 0) {
    throw new Error(`${file}: no ${markerLine('BEGIN', name, group)} block`)
  }
  const notice = isWebsiteDoc(file) ? [] : [GENERATED_NOTICE, '']
  for (const block of matching.toReversed()) {
    const body = render(block)
    if (!body.trim() && !allowEmpty) {
      throw new Error(
        `${file}: ${markerLine('BEGIN', block.name, block.group)} rendered nothing. Fix the generator's source read rather than publish an empty block.`,
      )
    }
    lines.splice(
      block.begin + 1,
      block.end - block.begin - 1,
      '',
      ...(body.trim() ? [...notice, ...body.split('\n'), ''] : []),
    )
  }
  return lines.join('\n')
}
