/**
 * What `check-doc-imports.ts` offers to check, and — mostly — what it declines.
 *
 * Every rule under test is a reason to SKIP, which is what makes them worth
 * pinning: a skip that widens does not produce a failure anyone sees. It stops
 * a class of reference being checked, and the run goes on reporting that all
 * references resolve. Both halves of this module were found that way rather
 * than by a failing build — three roots' worth of paths were unanchored and
 * silently unchecked, and a citation that wrapped before its § was skipped for
 * long enough that the heading it named got reworded underneath it.
 */
import { anchorOf, citationText, repoPathRefs } from './docReferenceMatching.ts'

describe('repoPathRefs', () => {
  test('finds a plain repo path', () => {
    expect(repoPathRefs('see `packages/core/src/util` for it')).toEqual([
      'packages/core/src/util',
    ])
  })

  test('finds the single-segment roots the check was missing', () => {
    expect(repoPathRefs('run `scripts/check-docs.ts`')).toEqual([
      'scripts/check-docs.ts',
    ])
    expect(
      repoPathRefs('`website/scripts/check-specs.ts` ratchets it'),
    ).toEqual(['website/scripts/check-specs.ts'])
    expect(repoPathRefs('`test_data/volvox/volvox.bam`')).toEqual([
      'test_data/volvox/volvox.bam',
    ])
  })

  // The reason a single-segment root needs a lookbehind at all: these docs cite
  // sibling repos, and `scripts/` is what everyone calls their script directory.
  test('does not match a path inside a longer foreign path', () => {
    expect(
      repoPathRefs('repro `~/src/jb2bench/scripts/render/multibam.ts`'),
    ).toEqual([])
    expect(repoPathRefs('`jb2bench/scripts/ldbench.ts`')).toEqual([])
    expect(
      repoPathRefs('`jbrowse-plugin-graphgenomeview/scripts/build-wasm.sh`'),
    ).toEqual([])
  })

  test('skips an elision marker', () => {
    expect(
      repoPathRefs('`plugins/canvas/.../renderLifecycleGate.test.ts`'),
    ).toEqual([])
  })

  // A metacharacter is not in the path class, so the match stops at it and
  // leaves a prefix that was never meant to resolve.
  test('skips a glob, a brace expansion and a placeholder', () => {
    expect(repoPathRefs('regenerated by `scripts/build_*.sh`')).toEqual([])
    expect(
      repoPathRefs('`website/scripts/specs/graph-{fixtures,ecoli}.ts`'),
    ).toEqual([])
    expect(repoPathRefs('mark it `scripts/build_<topic>.sh`')).toEqual([])
  })

  test('skips a path inside a GitHub blob URL, which scanBlobAnchors owns', () => {
    expect(
      repoPathRefs(
        'https://github.com/GMOD/jbrowse-components/blob/main/packages/core/src/index.ts',
      ),
    ).toEqual([])
  })

  test('skips a path named at a revision, where absence is the point', () => {
    expect(
      repoPathRefs('`git show abc123:agent-docs/reference/GONE.md`'),
    ).toEqual([])
  })

  test('strips trailing punctuation so a sentence-final path still resolves', () => {
    expect(repoPathRefs('it lives in `packages/core/src/util`.')).toEqual([
      'packages/core/src/util',
    ])
  })

  test('finds every path on a line naming two', () => {
    expect(
      repoPathRefs('`packages/core/src/a.ts` and `plugins/maf/src/b.ts`'),
    ).toEqual(['packages/core/src/a.ts', 'plugins/maf/src/b.ts'])
  })
})

describe('anchorOf', () => {
  // A directory OF packages needs two segments before the anchor means
  // anything; a single-segment root is its own anchor.
  test('takes two segments under a packages directory', () => {
    expect(anchorOf('plugins/myplugin/src/index.ts')).toBe('plugins/myplugin')
    expect(anchorOf('packages/core/src/util')).toBe('packages/core')
  })

  test('takes one segment for a single-segment root', () => {
    expect(anchorOf('scripts/check-docs.ts')).toBe('scripts')
    expect(anchorOf('test_data/volvox/volvox.bam')).toBe('test_data')
  })
})

// Every fixture below interpolates the filename rather than writing it out.
// check-doc-imports scans this directory's source for `§` and checks whatever
// citation it finds, so a fixture spelled literally is a citation — and one
// deliberately split across an array literal parses as a doc called
// `ARCHITECTURE.md` cited at §"Display', 'stacks". Keeping the `.md` off the
// raw line is what stops a test about citations from failing the checker it
// tests.
const DOC = 'ARCHITECTURE.md'
const SECTION = 'Display stacks'

describe('citationText', () => {
  test('leaves a citation that fits on one line alone', () => {
    const lines = [`see ${DOC} §"${SECTION}" for it`]
    expect(citationText(lines, 0)).toBe(lines[0])
  })

  // The break that was already handled.
  test('joins a citation wrapping inside the quoted title', () => {
    const lines = [`see ${DOC} §"Display`, 'stacks" for it']
    expect(citationText(lines, 0)).toContain(`§"${SECTION}"`)
  })

  // The break that was not, and the common one at an 80-column hand wrap.
  test('joins a citation wrapping between the filename and the §', () => {
    const lines = [`see ${DOC}`, `§"${SECTION}" for it`]
    expect(citationText(lines, 0)).toContain(`${DOC} §"${SECTION}"`)
  })

  test('strips a comment marker so one path serves prose and comments', () => {
    const lines = [` * see ${DOC}`, ` * §"${SECTION}"`]
    expect(citationText(lines, 0)).toContain(`${DOC} §"${SECTION}"`)
  })

  test('does not run off the end of the file', () => {
    expect(citationText([`trailing ${DOC}`], 0)).toBe(`trailing ${DOC} `)
  })
})
