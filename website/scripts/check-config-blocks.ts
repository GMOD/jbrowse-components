// Enforce how the hand-written docs present a JSON config block, the convention
// in website/docs/CLAUDE.md:
//
//   * a complete track config is tagged ```json addtrack, a complete assembly
//     config ```json addassembly, and a lone `defaultSession` ```json session,
//     so each renders the Config/CLI tab pair (scripts/check-config-cli.ts then
//     proves the derived command runs).
//     Every whole track config is flagged, because every one has tabs to
//     render: a config `deriveAddTrack` returns null for (a synteny adapter's
//     query/target slots, MultiWiggleAdapter subadapters, any custom
//     `displays`) still gets the verbatim `add-track-json` command and the
//     Desktop paste, which is the route a reader owning no config.json has.
//     An ASSEMBLY the derivation refuses is exempt, and has to be: there is no
//     `add-assembly-json` to fall back on, so tagging it renders no widget at
//     all and only leaves the author an ALLOWED entry that records nothing;
//   * no block presents a bare adapter or display object at the top level. Such
//     a blob reads as a track config — it even has a `type` — but pasting it
//     into `tracks` loads nothing. Nest it in the track/assembly it belongs to,
//     or, when the excerpt really is about the slot, prefix the parent key
//     (`"adapter": { ... }`), which this check accepts because the fence then
//     isn't standalone JSON;
//   * every key a track/assembly block names is one its type declares, checked
//     with `jbrowse validate`'s own checker. Nothing else covered this:
//     check-doc-slots reads `displayDefaults` keys and slot VALUES, and
//     check-config-cli hands the block to `add-track-json` verbatim, so a key
//     nested in an `adapter` or a `displays` entry passed both — as JBrowse
//     itself does, since it ignores keys it does not declare. It found a
//     tutorial telling readers to put `layout` (display state, not a config
//     slot) in a track's `displays`, where it does nothing at all.
//
// Autogenerated pages (config/, models/, api/) are skipped: their examples come
// from `#example` JSDoc in plugin source, so a violation there is fixed in the
// source, not here. ALLOWED lists the deliberate exceptions.
//
// Run: `pnpm check-config-blocks`

import remarkGfm from 'remark-gfm'
import remarkParse from 'remark-parse'
import { unified } from 'unified'
import { visit } from 'unist-util-visit'

import { validateConfig } from '../../products/jbrowse-cli/src/commands/validate/validateConfig.ts'
import { deriveAddAssembly } from '../src/lib/derive-add-assembly.ts'
import { defaultSessionObject } from '../src/lib/derive-set-default-session.ts'
import {
  isAddassembly,
  isAddtrack,
  isSession,
} from '../src/lib/remark-config-cli-tabs.ts'
import { docsMatching, reportProblems } from './check-utils.ts'
import { docRelative, docsDir } from './paths.ts'

// A doc block is one track or one assembly, so wrap it in the smallest config
// that makes it checkable. A track's `assemblyNames` are stubbed out as real
// assemblies, since an undefined-assembly error would otherwise fire on every
// block in the corpus and say nothing about the block.
const stubAssemblies = (names: string[]) =>
  names.map(n => ({ name: n, uri: `${n}.2bit` }))

// Every assembly the tracks of a partial config name.
function assemblyNamesIn(parsed: Record<string, unknown>) {
  const tracks = Array.isArray(parsed.tracks) ? parsed.tracks : []
  const names = new Set<string>()
  for (const t of tracks) {
    for (const n of (isRecord(t) && Array.isArray(t.assemblyNames)
      ? t.assemblyNames
      : []) as unknown[]) {
      if (typeof n === 'string') {
        names.add(n)
      }
    }
  }
  return [...names]
}

function validateBlock(parsed: Record<string, unknown>, kind: string) {
  // A whole config already is one — including "the smallest config" and "a
  // complete config" at the top of the cookbook, which are the most copied
  // blocks in the docs and the ones a bare track/assembly check skips, since
  // neither has a `trackId` at the top level.
  //
  // A partial one (`{ plugins, tracks }`, showing what to add to a config the
  // page set up earlier) gets the same stub assemblies a bare track does, so
  // the cross-reference checks stay quiet about an assembly the excerpt was
  // never going to repeat. Slot checking, which is the point here, is
  // unaffected.
  if (kind === 'config') {
    if (Array.isArray(parsed.assemblies)) {
      return validateConfig(parsed)
    }
    const result = validateConfig({
      ...parsed,
      assemblies: stubAssemblies(assemblyNamesIn(parsed)),
    })
    // Whatever the excerpt says about ITS keys stands; what the surrounding
    // config says about assemblies is not its to answer. An excerpt showing
    // only `plugins` (with `tracks: []`, so it is still shaped like a config)
    // would otherwise be told it has no assemblies, which is true of the
    // fragment and false of the page.
    return {
      ...result,
      problems: result.problems.filter(p => !p.where.startsWith('assemblies')),
    }
  }
  const names = Array.isArray(parsed.assemblyNames)
    ? (parsed.assemblyNames as string[])
    : ['volvox']
  return validateConfig(
    kind === 'assembly'
      ? { assemblies: [parsed], tracks: [] }
      : { assemblies: stubAssemblies(names), tracks: [parsed] },
  )
}

// blocks that stay untagged on purpose, keyed `<docs-relative path>#<trackId or
// assembly name>` so an exception survives the block moving down its page
const ALLOWED = new Map([
  [
    'tutorials/cli_desktop.md#sample',
    'shows what the CLI already wrote, not a track to add',
  ],
  [
    'config_guides/authentication.md#private_bam',
    'its subject is the internetAccountId, and the account it names is declared in a top-level internetAccounts array no fence can carry. A paste route would read the file unauthenticated, which is the failure the section explains',
  ],
])

const parser = unified().use(remarkParse).use(remarkGfm)

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

// A parsed block is a complete track config when it carries the three things
// `tracks` entries always have; an assembly when it has a name plus a sequence
// (or the flattest `uri` shorthand for one).
function shape(obj: Record<string, unknown>) {
  const type = typeof obj.type === 'string' ? obj.type : ''
  const keys = Object.keys(obj)
  return Array.isArray(obj.assemblies) || Array.isArray(obj.tracks)
    ? 'config'
    : type.endsWith('Adapter')
      ? 'adapter'
      : type.endsWith('Display')
        ? 'display'
        : obj.trackId && obj.adapter && obj.type
          ? 'track'
          : obj.name && (obj.sequence ?? obj.uri)
            ? 'assembly'
            : keys.length > 0 &&
                keys.every(k => k === 'displayDefaults' || k === 'displays')
              ? 'fragment'
              : 'other'
}

const problems: string[] = []
// Weaker than `node.lang === 'json'`, which is read off this same fence line.
const JSON_FENCE = /^\s*(?:```|~~~)json\b/m

for (const { file, text } of docsMatching(docsDir, JSON_FENCE)) {
  const rel = docRelative(file)
  if (/^(config|models|api)\//.test(rel) || rel.endsWith('CLAUDE.md')) {
    continue
  }
  visit(parser.parse(text), 'code', node => {
    if (node.lang !== 'json') {
      return
    }
    let parsed: unknown
    try {
      parsed = JSON.parse(node.value)
    } catch {
      // not standalone JSON: a key-prefixed excerpt (`"adapter": { ... }`),
      // which is unambiguous about where it goes
      return
    }
    if (!isRecord(parsed)) {
      return
    }
    const where = `${rel}:${node.position?.start.line ?? 0}`
    const id = parsed.trackId ?? parsed.name
    const kind = shape(parsed)
    const tagged = isAddtrack(node) || isAddassembly(node)
    if ((kind === 'adapter' || kind === 'display') && !tagged) {
      problems.push(
        `  ${where}`,
        `    → bare ${kind} object at the top level (type: ${String(parsed.type)}).`,
        `      Show the whole track/assembly it belongs to, or prefix the parent key.\n`,
      )
    } else if (kind === 'fragment') {
      problems.push(
        `  ${where}`,
        `    → only \`${Object.keys(parsed).join('`/`')}\`, so there is no track to paste it into.`,
        `      Restate the whole track config with the slot in place (same trackId`,
        `      as the track it replaces), or prefix the parent key.\n`,
      )
    } else if (kind === 'track' || kind === 'assembly' || kind === 'config') {
      // Slot names, run through the same checker `jbrowse validate` uses. The
      // gap this closes: check-doc-slots looks at `displayDefaults` keys and at
      // slot VALUES, and check-config-cli takes the block verbatim through
      // `add-track-json`, so a misspelled key inside an `adapter`
      // (`bamLocatoin`) survives both — and survives JBrowse itself, which
      // ignores keys it does not declare. A doc example is the worst place for
      // that, since it is copied.
      for (const p of validateBlock(parsed, kind).problems) {
        if (p.level === 'error') {
          problems.push(
            `  ${where}`,
            `    → ${p.where ? `${p.where}: ` : ''}${p.message}\n`,
          )
        }
      }
    }
    if ((kind === 'track' || kind === 'assembly') && !tagged) {
      // A track always has a tab to render: `deriveAddTrack` refusing it only
      // picks the `add-track-json` label, and the Desktop tab is the same
      // pasted JSON whatever the CLI can express. So the tag is required for
      // every whole track config, and only an assembly is exempt when the
      // derivation refuses it, since `add-assembly` has no JSON fallback and a
      // tag there renders no widget at all.
      const derivable = kind === 'track' || deriveAddAssembly(parsed) !== null
      if (derivable && !ALLOWED.has(`${rel}#${String(id)}`)) {
        problems.push(
          `  ${where}`,
          `    → complete ${kind} config with no \`addtrack\`/\`addassembly\` tag,`,
          `      so it renders without its CLI tab. Tag the fence, or add it to`,
          `      ALLOWED in scripts/check-config-blocks.ts with the reason.\n`,
        )
      }
    }
    // `shape` reads a lone `defaultSession` as 'other', so this is its own
    // branch rather than a case there. The derivation is the gate for the same
    // reason it is above: a block carrying more than the session (a whole
    // config.json, or one paired with preConfiguredSessions) has no command
    // that writes all of it, so there is nothing to tag it for.
    if (!isSession(node) && defaultSessionObject(parsed) !== null) {
      problems.push(
        `  ${where}`,
        `    → lone \`defaultSession\` with no \`session\` tag, so it renders`,
        `      without its set-default-session tab. Tag the fence.\n`,
      )
    }
  })
}

if (problems.length) {
  problems.unshift(
    `Found JSON config blocks that break the docs convention (see website/docs/CLAUDE.md):\n`,
  )
}
reportProblems(
  problems,
  'All hand-written JSON config blocks are whole configs, tagged for their CLI tab.',
)
