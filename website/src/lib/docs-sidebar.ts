import { entrySlug } from './doc-slug.ts'
import { GUIDE_CATEGORY_ORDER, guideRank } from './guide-categories.ts'
import sidebarsJson from '../../sidebars.json'

export { entrySlug }

export interface SidebarLink {
  type: 'link'
  label: string
  href: string
  slug: string
}

export interface SidebarGroup {
  type: 'group'
  label: string
  items: SidebarEntry[]
  // A collapsible group whose summary is itself a link to a page (the showcase
  // top-level entries: Gallery, Demos). `slug` marks it active/open when the
  // current page matches. Plain docs categories omit both.
  href?: string
  slug?: string
}

export type SidebarEntry = SidebarLink | SidebarGroup

interface DocEntry {
  id: string
  data: { title: string; sidebar_label?: string; guide_category?: string }
}

type DocusaurusSidebarItem =
  | string
  | { type: 'category'; label: string; items: DocusaurusSidebarItem[] }
  | { type: 'autogenerated'; dirName: string }
  // An explicit link to a page that isn't a docs-collection entry (e.g. the
  // auto-listed /docs/tutorials/ landing page). `to` is a doc-relative slug so
  // the base URL is applied the same way as for doc links.
  | { type: 'link'; label: string; to: string }

export function containsSlug(entry: SidebarEntry, slug: string): boolean {
  return entry.type === 'link'
    ? entry.slug === slug
    : entry.slug === slug ||
        entry.items.some(child => containsSlug(child, slug))
}

function docLabel(entry: DocEntry): string {
  return entry.data.sidebar_label ?? entry.data.title
}

function docHref(baseUrl: string, slug: string): string {
  return `${baseUrl}/docs/${slug}${slug ? '/' : ''}`
}

// The sidebar is deliberately at most one level deep: a top-level category,
// then pages. Subcategories used to be nested collapsible groups, which hid
// most of the docs behind a closed heading — a reader scrolls past a section
// they don't want far more reliably than they open one they can't see. So a
// subcategory becomes a "<Subcategory>: " prefix on the sidebar label instead,
// keeping the grouping visible in a flat, scannable list. The landing pages
// (guide indexes, /docs/config, /docs/models) still render real sections.

// Rewrites a "<Category> -> <Name>" sidebar_label (config and state-model docs
// both emit this format) to "<Category>: <Name>". Sorting on the rewritten
// label keeps a category's pages contiguous.
function prefixByCategory(links: SidebarLink[]): SidebarLink[] {
  return links
    .map(link => {
      const match = /^(.+?)\s*->\s*(.+)$/.exec(link.label)
      return match
        ? { ...link, label: `${match[1]!.trim()}: ${match[2]!.trim()}` }
        : link
    })
    .sort((a, b) => a.label.localeCompare(b.label))
}

// Prefixes a guide directory's pages with their `guide_category` frontmatter
// and orders them by the same buckets, in the same order, the guide's landing
// page uses (see src/lib/guide-categories.ts). `docs` and `links` are aligned
// by position. Categories not in `categoryOrder` (a stray value) fall to the
// end alphabetically rather than vanishing.
function prefixByGuideCategory(
  dirName: string,
  docs: DocEntry[],
  links: SidebarLink[],
  categoryOrder: string[],
): SidebarLink[] {
  const byCategory = new Map<string, SidebarLink[]>()
  for (let i = 0; i < docs.length; i++) {
    const category = docs[i]!.data.guide_category ?? 'Other'
    if (!byCategory.has(category)) {
      byCategory.set(category, [])
    }
    byCategory.get(category)!.push({
      ...links[i]!,
      label: `${category}: ${links[i]!.label}`,
    })
  }

  // `links` arrives alphabetical by label, so a stable sort on the curated rank
  // alone lifts the lead pages and leaves everything else as it was.
  for (const inCategory of byCategory.values()) {
    inCategory.sort(
      (a, b) => guideRank(dirName, a.slug) - guideRank(dirName, b.slug),
    )
  }

  const ordered = categoryOrder.filter(c => byCategory.has(c))
  const extra = [...byCategory.keys()]
    .filter(c => !categoryOrder.includes(c))
    .sort()
  return [...ordered, ...extra].flatMap(category => byCategory.get(category)!)
}

function getAutoItems(
  dirName: string,
  allDocs: DocEntry[],
  baseUrl: string,
): SidebarEntry[] {
  const dirDepth = dirName.split('/').length + 1
  const docs = allDocs
    .filter(d => {
      const slug = entrySlug(d.id)
      return (
        slug.startsWith(`${dirName}/`) && slug.split('/').length === dirDepth
      )
    })
    .sort((a, b) => docLabel(a).localeCompare(docLabel(b)))

  const links: SidebarLink[] = docs.map(d => {
    const slug = entrySlug(d.id)
    return {
      type: 'link',
      label: docLabel(d),
      href: docHref(baseUrl, slug),
      slug,
    }
  })

  const categoryOrder = GUIDE_CATEGORY_ORDER[dirName]
  return dirName === 'config' || dirName === 'models'
    ? prefixByCategory(links)
    : categoryOrder
      ? prefixByGuideCategory(dirName, docs, links, categoryOrder)
      : links
}

function convertItems(
  items: DocusaurusSidebarItem[],
  allDocs: DocEntry[],
  baseUrl: string,
  docsBySlug: Map<string, DocEntry>,
): SidebarEntry[] {
  const result: SidebarEntry[] = []

  for (const item of items) {
    if (typeof item === 'string') {
      const slug = entrySlug(item)
      const resolvedSlug = slug === 'introduction' ? '' : slug
      const entry = docsBySlug.get(resolvedSlug)
      const label = entry ? docLabel(entry) : slug
      result.push({
        type: 'link',
        label,
        href: docHref(baseUrl, resolvedSlug),
        slug: resolvedSlug,
      })
    } else if (item.type === 'autogenerated') {
      result.push(...getAutoItems(item.dirName, allDocs, baseUrl))
    } else if (item.type === 'link') {
      const slug = entrySlug(item.to)
      result.push({
        type: 'link',
        label: item.label,
        href: docHref(baseUrl, slug),
        slug,
      })
    } else {
      result.push({
        type: 'group',
        label: item.label,
        items: convertItems(item.items, allDocs, baseUrl, docsBySlug),
      })
    }
  }

  return result
}

export function buildSidebar(
  allDocs: DocEntry[],
  baseUrl: string,
): SidebarEntry[] {
  const docsBySlug = new Map(allDocs.map(d => [entrySlug(d.id), d]))
  return convertItems(
    sidebarsJson.sidebar as DocusaurusSidebarItem[],
    allDocs,
    baseUrl,
    docsBySlug,
  )
}

// Ancestor group labels of a page, outermost first ("User guide"), for the
// breadcrumb above its h1. With the sidebar flattened to one level this is
// normally a single label, but it stays a walk so a future nested group is
// handled. Derived from the resolved sidebar for the same reason
// buildSearchCategoryMap is: which group holds a page is only known after
// buildSidebar expands the autogenerated directories, so a second walk of the
// raw sidebars.json could not see it, and any hand-listed copy would drift when
// a page moves. The current page itself is not included
// (the h1 right below already names it), and a top-level page like FAQ has no
// ancestors and so gets an empty trail.
export function breadcrumbTrail(
  sidebar: SidebarEntry[],
  slug: string,
): string[] {
  for (const entry of sidebar) {
    // `entry.items.some` rather than `containsSlug(entry, …)` so a group that
    // *is* the page (a showcase group with its own href) isn't its own ancestor
    if (
      entry.type === 'group' &&
      entry.items.some(c => containsSlug(c, slug))
    ) {
      return [entry.label, ...breadcrumbTrail(entry.items, slug)]
    }
  }
  return []
}

function flattenLinks(entry: SidebarEntry): SidebarLink[] {
  return entry.type === 'link' ? [entry] : entry.items.flatMap(flattenLinks)
}

// Flattens the sidebar into ordered `## <section>` buckets for /llms.txt. Each
// top-level group is a section; standalone top-level links (Introduction,
// Cookbook, CLI, FAQ) merge into one "General" section (else each emits a
// duplicate "## General"). `has` filters to slugs with an emitted page; a slug
// appears in its first section only.
export function sidebarSections(
  sidebar: SidebarEntry[],
  has: (slug: string) => boolean,
): { label: string; links: SidebarLink[] }[] {
  const seen = new Set<string>()
  const fresh = (links: SidebarLink[]) =>
    links.filter(link => {
      const ok = has(link.slug) && !seen.has(link.slug)
      if (ok) {
        seen.add(link.slug)
      }
      return ok
    })

  const sections: { label: string; links: SidebarLink[] }[] = []
  const general: SidebarLink[] = []
  let generalIdx = -1
  for (const entry of sidebar) {
    if (entry.type === 'group') {
      const links = fresh(flattenLinks(entry))
      if (links.length) {
        sections.push({ label: entry.label, links })
      }
    } else {
      if (generalIdx === -1) {
        generalIdx = sections.length
        sections.push({ label: 'General', links: [] })
      }
      general.push(entry)
    }
  }
  if (generalIdx !== -1) {
    sections[generalIdx]!.links = fresh(general)
    if (!sections[generalIdx]!.links.length) {
      sections.splice(generalIdx, 1)
    }
  }
  return sections
}

// The "showcase" pages (Features / Plugins / Gallery / Demos) hang off the same
// sidebar as the docs, so navigation is identical everywhere on the site.
// They're grouped under one "Showcase" category rather than sitting as four
// top-level links.
export function buildShowcaseGroups(baseUrl: string): SidebarEntry[] {
  const pageUrl = (path: string) => `${baseUrl}/${path}/`
  return [
    {
      type: 'group',
      label: 'Showcase',
      items: [
        {
          type: 'link',
          label: 'Features',
          href: pageUrl('features'),
          slug: 'features',
        },
        {
          type: 'link',
          label: 'Plugins',
          href: pageUrl('plugin_store'),
          slug: 'plugin_store',
        },
        {
          type: 'link',
          label: 'Gallery',
          href: pageUrl('gallery'),
          slug: 'gallery',
        },
      ],
    },
  ]
}

// Showcase is spliced in after the last collapsible category rather than
// appended, so the nav renders as one run of categories followed by one run of
// plain links. sidebars.json keeps its own standalone entries (the embedding
// pages, the CLI tools, FAQ) at the end for the same reason: a link with no
// disclosure arrow sitting between two categories reads as a rendering bug, and
// interleaving the two shapes makes neither run scannable.
export function buildSiteSidebar(
  allDocs: DocEntry[],
  baseUrl: string,
): SidebarEntry[] {
  const docs = buildSidebar(allDocs, baseUrl)
  const lastGroup = docs.findLastIndex(entry => entry.type === 'group')
  return [
    ...docs.slice(0, lastGroup + 1),
    ...buildShowcaseGroups(baseUrl),
    ...docs.slice(lastGroup + 1),
  ]
}

// The /search page groups results into a handful of broad audience filters.
// Rather than hand-list which slugs belong to which filter (a second copy of
// the categorization in sidebars.json that silently drifts whenever a page
// moves — see e.g. the 2026-07 sidebar reorg), derive it from the same
// top-level sidebar categories every doc is already placed in.
export type SearchCategory =
  'user' | 'config' | 'developer' | 'autogen' | 'other'

const TOP_LEVEL_CATEGORY_BUCKETS: Record<string, SearchCategory> = {
  'User guide': 'user',
  Tutorials: 'user',
  Configuration: 'config',
  Development: 'developer',
  'Reference: Config schema': 'autogen',
  'Reference: State models': 'autogen',
  'Reference: Exported functions': 'autogen',
}
// "Embedding", "Command line tools" and the loose introduction/faq links are
// intentionally unmapped: they fall through to the always-shown 'other' bucket
// so no search filter can hide them.

// Pages whose search-filter bucket is deliberately not their sidebar category.
// The cookbook is a top-level sidebar link (it is the page people arrive
// looking for, not a chapter of the config guide) but its content is config, so
// the "Config guides" filter should still return it; quickstart_adminserver is
// not in the sidebar at all (check-sidebar.ts lists it as intentionally
// unlisted, reached from user_guides/basic_usage.md) and reads as an ops topic.
// Keep this list short — most classification should come from
// TOP_LEVEL_CATEGORY_BUCKETS.
const SEARCH_CATEGORY_OVERRIDES: Record<string, SearchCategory> = {
  cookbook: 'config',
  quickstart_adminserver: 'developer',
}

function entrySlugsOf(entry: SidebarEntry): string[] {
  return entry.type === 'link'
    ? [entry.slug]
    : entry.items.flatMap(entrySlugsOf)
}

export function buildSearchCategoryMap(
  allDocs: DocEntry[],
): Record<string, SearchCategory> {
  // Walk the same resolved sidebar the pages render from: each top-level
  // category becomes a group with that category's label, and every slug beneath
  // it inherits the group's bucket. Deriving from buildSidebar (rather than a
  // second walk of the raw sidebars.json) keeps a page's search bucket in sync
  // with its actual sidebar placement.
  const map: Record<string, SearchCategory> = {}
  for (const entry of buildSidebar(allDocs, '')) {
    const bucket =
      entry.type === 'group'
        ? TOP_LEVEL_CATEGORY_BUCKETS[entry.label]
        : undefined
    if (bucket) {
      for (const slug of entrySlugsOf(entry)) {
        map[slug] = bucket
      }
    }
  }
  Object.assign(map, SEARCH_CATEGORY_OVERRIDES)
  return map
}
